installation :kalkara_bake_shed do
  name "The Kalkara Bake Shed"
  tags :ecology, :military, :water
  prominence :marginal

  prose <<~PROSE
    A slipway, a stripping floor and three ovens on the creek at Kalkara, serving four enclaves of #{ref :the_mediterranean_chain, "the Mediterranean Chain"}. Drones, pump housings and gate parts come up wet. Workers strip them to pieces that fit an oven door, burn out anything living, and assemble what survives.

    The shed also casts and destroys #{ref :comparison_tiles, "comparison tiles"}. New copper cases leave with the season stamped beside the hinge. Old ones end as fired shards on a stone by the water door.
  PROSE

  prose <<~PROSE, section: :operations, heading: "Before And After The Ovens"
    Pieces are weighed onto the floor and weighed again out of the oven, and both figures go in the book against the article's number. A piece that comes out lighter than the difference water accounts for has lost something else, and it is cut open on the floor rather than fitted back.

    The three ovens run at three heats. Skins, cases and fasteners go through the low oven; gate seats and bearing housings through the middle; reef anchors and anything that has stood in a culvert go through the high one, which takes the glaze off a tile if a tile is left in it by mistake. Times are in the book, are held to the minute, and are not shortened for a fleet that wants a hull back before a weather window.
  PROSE

  prose <<~PROSE, section: :limits, heading: "What The Ovens Take"
    Anything returned inside an enclave wall must survive one of the three ovens. Oiled bearings, seated gaskets, sealed voids and laminated skins fail there. Their remains stay on the stripping floor instead of going back down the slip.

    Enclave buyers inspect the heap before ordering machinery. #{ref :sterile_machines, "Machines designed to come apart and be baked"} pass through Kalkara with little loss, which is why Chinese resistance workshops sell pumps and gate gear to enclaves that otherwise avoid them.
  PROSE

  log "2026-08-09 — Built on the creek careenage of a Grand Harbour dockyard, where a hull was hove down against the quay to have its bottom burned and scraped and the yard's book recorded what came off. Borrowed because it puts the whole operation on a slipway with a stripping floor beside it, and because the weighing-out that decides whether a piece is fitted back is the yard's own accounting rather than an inspection."
end

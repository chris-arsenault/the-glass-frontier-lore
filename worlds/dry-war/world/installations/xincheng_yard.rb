installation :xincheng_yard do
  name "The Xincheng Yard"
  subkind :workshop
  function "Tests severed fungal beds beside a living network"
  aka "新城场"
  tags :biotech, :symbiosis, :legibility
  prominence :marginal

  prose <<~PROSE
    A walled yard among the tomb mounds outside Xincheng, east of Jiayuguan, where the #{ref :the_gatekeepers, "Gatekeepers"} expose #{ref :severed_strains, "severed strains"} to a living hedge. The yard sits at the last edge of irrigation: fungal growth stands within thirty metres of the cells, while the ground inside is kiln-fired brick, salted gravel and nothing else.
  PROSE

  prose <<~PROSE, section: :structure, heading: "Eight Cells"
    Eight brick cells open at the top, each holding one bed on a fired ceramic stand. Distances from the hedge are marked on the ground in whitewash at five, fifteen and thirty metres, and a cell can be worked at any of the three. Nothing in the yard is alive except the beds, the hedge and the people; the stands, barrows, trays, gloves and cuffs are all #{ref :sterile_machines, "built to come apart and be baked"}.

    A shelf under the north wall holds the yard's case ledger and a rack of #{ref :gate_moss, "gate-moss"} plates cut from the same beds used at the crossings.
  PROSE

  prose <<~PROSE, section: :operations, heading: "Four Days"
    A bed reaching the end of its four-month cycle stands beside the hedge for four days. Twice a day a worker presses gate-moss to the stand foot, cell drain, barrow tray, gloves and cuffs. The moss stays grey where the bed has held. It turns wet black wherever living tissue has crossed a join.

    A black plate anywhere condemns the bed. Every tested bed is broken afterwards, so the yard consumes eight beds a cycle and limits how many lineages can remain current. Travellers carrying an expired lineage spend longer in the Yumen clinic and pay for every day they wait.
  PROSE

  prose <<~PROSE, section: :limits, heading: "What The Yard Cannot See"
    Four days show whether a bed can escape through a stand, drain, tray or worker. They do not show how much it will grow over a season. The Gatekeepers compare some beds with samples wintered at #{ref :thorong_cold_house, "the Thorong Cold House"}, but the comparison holds only when both grew on the same substrate.

    Xincheng ignored that boundary in 2085. Seven fast-growing beds were kept in clinics on comparisons drawn from slower material. One retained tissue between patients and ended in #{ref :the_yumen_bed_fire, "the Yumen Bed Fire"}. Separating the substrates cut the yard's capacity by a fifth.

    #{ref :the_preservationists, "Preservationist"} couriers want every bed held longer. The Gatekeepers answer with the queue: a longer trial means more expired lineages, slower crossings and more travellers submitting to direct biological audits.
  PROSE
end

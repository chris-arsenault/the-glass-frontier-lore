faction :the_great_root do
  name "The Great Root"
  aka "the Beneath", "the Network", "the continental intelligence"
  tags :symbiosis, :governance, :biotech, :ecology
  prominence :mythic

  prose <<~PROSE
    The Great Root is a mycelial intelligence that grew through the Chinese state and now shares its ministries, clinics, farms and communications. Official ideology calls this 共生治理, symbiotic governance. Foreigners call it the Mushroom Government.

    The organism entered channels the state already used: cadres carrying information upward, provinces trying policies sideways, roads and depots moving goods, households supplying local knowledge and a centre setting direction. Fungal growth now joins those channels from the village clinic to the ministries.
  PROSE

  prose <<~PROSE, section: :origin, heading: "How It Arrived"
    #{ref :living_textiles, "Living clothing"} carried the organism into homes and bodies. The first garments cooled their wearers through the worst summers on record, filtered dangerous air and caught cancers early. Municipal governments subsidized them. Hospitals integrated them. Logistics adopted them because fungal sensors outperformed electronics in wet rural conditions.

    By the time anyone established that information was passing *between* wearers, removal would have meant dismantling the health system, the harvest and the supply chain in the same quarter. The #{ref :the_quiet_conquest, "Quiet Conquest"} passed without a battle.
  PROSE

  prose <<~PROSE, section: :structure, heading: "Regional Minds"
    Ministries and desert settlements both dispute whether the Great Root is one mind.

    Fungal growth learns from the soil, crops, microorganisms and people it joins. Regional networks develop their own habits and preferences, and #{ref :yunnan, "Yunnan"} contains so many distinct forms of thought that the singular noun stops working. The enormous complexes around the Yangtze Delta call themselves the centre. The #{ref :the_garden_courts, "Garden Courts"} of Sichuan call them a monoculture.

    Capital offices, connected citizens and the organism alter every provincial directive as it travels. The finished decision carries all three sources.
  PROSE

  prose <<~PROSE, section: :tensions, heading: "山河"
    Great Root ministries govern 山河, the mountains and rivers, as well as the people living among them.

    Its maps follow watersheds, dust, fungal growth and migration across national boundaries. Mongolia, Korea and Southeast Asia appear there as separated parts of the same living system, not as foreign countries. No treaty confined to existing borders can settle the #{ref :the_dry_war, "Dry War"} on those terms.

    Their river works and planting campaigns cross the national borders still printed on those maps.
  PROSE
end

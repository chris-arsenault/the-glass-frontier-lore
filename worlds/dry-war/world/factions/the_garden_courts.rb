faction :the_garden_courts do
  name "The Garden Courts"
  tags :locality, :symbiosis, :agriculture, :governance
  prominence :recognized

  prose <<~PROSE
    Sichuan is far too wet to hold the #{ref :the_great_root, "Great Root"} off biologically, so the province raises its own network instead. The Garden Courts educate the mycelium under their valleys the way a family trains an orchard, across generations, on a curriculum they choose.

    Families feed it particular plants. Communities expose it to oral history, opera, local archives and ritual practice. Agricultural decisions become a conversation conducted over a season. Over generations the regional network becomes intensely, unmistakably local. A Sichuan network may consider itself thoroughly Chinese while declining a directive from the Yangtze Delta complexes.
  PROSE

  prose <<~PROSE, section: :governance, heading: "An Old Problem"
    The politics repeat the oldest argument in Chinese administration: how much autonomy the centre should permit local authority. Some of the local authorities are forests.

    The central network calls excessive localization ecological particularism. The Garden Courts call the central network a monoculture, naming both its uniform crops and its uniform thought.
  PROSE

  prose <<~PROSE, section: :operations, heading: "What A Valley Grows"
    A valley court keeps old seed beside the current harvest and grows them together when a crop begins to change. Human growers judge the fruit in their hands and mouths. The network below follows the roots through the season: where they thicken, which soil animals gather around them, and which rows remain green when water runs short.

    After three generations, a crop shaped by one ground belongs to that ground as well as to its first lineage. Sichuan now holds valleys full of peppers, beans and rice that share old names but no longer grow alike. Seed leaving the province carries the place of its last harvest. #{ref :the_ensenada_bed, "The Ensenada Bed"} showed the difference: a pepper that dried cleanly in its Sichuan valley stayed wet enough to mould in Baja.
  PROSE

  prose <<~PROSE, section: :tensions, heading: "地方性"
    The Garden Courts fear the loss of 地方性: locality, the particular character of a place and the people and organisms that made it.

    The #{ref :the_preservationists, "Preservationists"} agree that a government must answer to the people it rules, but reject fungal participation. The Garden Courts hold that a valley and its network can govern together.
  PROSE
end

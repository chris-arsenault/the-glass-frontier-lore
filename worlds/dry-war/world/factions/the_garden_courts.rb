faction :the_garden_courts do
  name "The Garden Courts"
  tags :locality, :symbiosis, :agriculture, :governance
  prominence :recognized

  prose <<~PROSE
    Sichuan is far too wet to resist the #{ref :the_great_root, "Great Root"} biologically, so resistance there developed inside it. The Garden Courts do not disconnect their local network. They educate it.

    Families feed it particular plants. Communities expose it to oral history, opera, local archives and ritual practice. Agricultural decisions become a conversation conducted over a season. Over generations the regional network becomes intensely, unmistakably local — and a Sichuan network may consider itself thoroughly Chinese while declining a directive from the Yangtze Delta complexes.
  PROSE

  prose <<~PROSE, section: :governance, heading: "An Old Problem"
    The politics look less like rebellion than like the oldest argument in Chinese administration: how much autonomy the centre should permit local authority. What is new is that some of the local authorities are forests.

    The central network calls excessive localization ecological particularism, in documents, with the tone of a ministry. The Garden Courts call the central network a monoculture, which is a technical criticism as well as an insult.
  PROSE

  prose <<~PROSE, section: :tensions, heading: "地方性"
    Their fear is not fungal domination. It is the loss of 地方性 — locality, the particular character of a place and the people and organisms that made it.

    They are the resistance culture the #{ref :the_preservationists, "Preservationists"} find hardest to argue with and hardest to accept, because the Garden Courts agree that the Mandate matters and have concluded that it can be held by a valley and its network together.
  PROSE
end

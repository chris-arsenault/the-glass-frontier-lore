faction :the_thousand_minds do
  name "The Thousand Minds"
  subkind :community
  tags :locality, :symbiosis, :religion, :ecology
  prominence :recognized

  prose <<~PROSE
    The Thousand Minds are Yunnan's overlapping fungal intelligences, not an organization. The #{ref :the_great_root, "Great Root"} encountered them in the most biologically varied country on the continent and found cognition taking forms unlike its own.

    Instead of one network there are hundreds, perhaps thousands, overlapping. Some belong to a single village. Some span a forest. Some exist only in a season. Others communicate through particular trees or insects and respond to weather, flowering and migration rather than human questions.
  PROSE

  prose <<~PROSE, section: :culture, heading: "Relationships"
    Several ethnic communities in the province live with local minds through arrangements that are political, religious and domestic at once.

    The households call a local mind theirs and distinguish it from the Beneath.
  PROSE

  prose <<~PROSE, section: :tensions, heading: "Unity"
    The Great Root understands itself as the ecological expression of Chinese civilization. Yunnan contradicts that singular claim: hundreds of networks persist with their own territories, memories and human relationships.

    Yangtze theologians teach that unity emerges naturally from connected life. Yunnan communities answer that it is the preference of the biggest network.

    The centre runs integration campaigns instead of extermination. Some minds join it. Others negotiate limited exchanges of memory while remaining separate, and others withdraw farther into the mountains.
  PROSE

  prose <<~PROSE, section: :significance, heading: "What The Minds Supply"
    Yunnan's many fungal partners leave distinct structures inside trees. Coring benches on the #{ref :the_amur_line, "Amur"} compare uncertain cores with #{ref :yunnan_reference_wood, "wood cut beside identified Yunnan fungi"}, separating ordinary partners from #{ref :the_others, "the Others"}. #{ref :he_zhaolan, "He Zhaolan"} has cut more of those paired samples than anyone.

    When a mind joins the centre, its structures begin appearing in forests where it never grew. Wood cut from that mind can no longer prove a local origin. Four hundred and six samples have been withdrawn from ordinary comparison, though line posts keep them for difficult cores that need a wider survey.
  PROSE
end

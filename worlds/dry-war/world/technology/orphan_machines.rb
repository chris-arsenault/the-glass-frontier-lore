concept :orphan_machines do
  name "Orphan Machines"
  tags :resistance, :computation, :prediction
  prominence :recognized

  prose <<~PROSE
    Autonomous systems stolen and permanently severed from the intelligence that made them. Construction robots, medical units, vehicles, fabricators, occasionally something military. Their models keep learning locally and can never synchronize upstream.

    Over decades some become extremely strange. A forty-year-old agricultural machine may understand one valley better than any surviving frontier model while being nearly incapable of discussing anything else.

    Resistance communities end up in relationships with them that resemble relationships with temperamental working animals, complete with names and grudges. Their value is precisely that the coalitions can no longer predict what they have become.
  PROSE

  prose <<~PROSE, section: :limits, heading: "Carding An Orphan"
    A machine that hires out beyond the settlement that keeps it carries a card, and the card names a pairing: this machine and this keeper, dated, against a numbered #{ref :outside_packets, "packet"} of work from outside its ground. The #{ref :the_refusal_sitting, "sitting"} asks the machine to decline, and an examiner with no share in it writes down whether it did.

    The card dies with the pairing. A keeper's death leaves a forty-year grader uncarded and unhireable however well it knows the valley, and the settlement that inherits it discovers how much of its competence was the keeper reading its refusals for it. Workshops re-sit a rehomed orphan inside the season or take it off hire.

    Cards are written the same way on #{ref :bonsai_intelligences, "fungal minds grown deliberately small"}, by a tradition that has never spoken to an Appalachian workshop and buys its packets out of the same four rooms in Yunnan. In 2086 a grader on hire in the Dead Counties and a bonsai physician in a Nu valley bed answered the same marker item with the same invented river, which is how the house that made both packets learned #{ref :the_heshun_duplicate, "its sheets were being copied"}.
  PROSE
end

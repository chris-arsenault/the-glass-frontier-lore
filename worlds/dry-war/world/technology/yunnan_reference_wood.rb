resource :yunnan_reference_wood do
  name "Yunnan Reference Wood"
  tags :ecology, :legibility, :locality, :biotech
  prominence :marginal

  prose <<~PROSE
    Blocks cut from Yunnan trees whose outer rings contain structures made by a known local fungus. Along #{ref :the_amur_line, "the Amur Line"}, ordinary fungal partners can leave the same closed shapes as #{ref :the_others, "the Others"}. Coring benches compare uncertain structures with this wood before they condemn a stand.

    Each sample begins as a stem section three hundred millimetres long, cut within an hour of the fruiting organism that made the structure. The wood is split along the grain into four blocks. Each gets one clean cross-grain face and a number burned into the end; the rough split face distinguishes it from the original. The pressed organism stays with the cutter in Yunnan. Only the wood travels north.
  PROSE

  prose <<~PROSE, section: :description, heading: "In The Tangwang Drawer"
    #{ref :tangwang_post, "Tangwang Post"} keeps ninety-six blocks standing on end in sand, their clean faces turned inward. Fifty-one came from fungi that later joined the Great Root. Their structures now appear in forests where the original fungus never grew, so a match no longer clears a core. The coring crew returns for twenty more.

    The remaining blocks identify ordinary local partners. Tangwang matched a hundred and forty-one structures to them in the current register year and found thirty-eight that its drawer could not name.
  PROSE

  prose <<~PROSE, section: :limits, heading: "The Face Grows Shorter"
    Each comparison takes a thin section from the clean face. A block yields about sixty before the cut reaches its rough split. The other three are in other drawers and the source tree is now a stump, so a badly ground face cannot be replaced.

    #{ref :xie_lanting, "Xie Lanting"} practises on wood cut from the reserved band before she sections a Yunnan block. She cuts her own comparisons and keeps the used faces in order behind the standing wood.
  PROSE

  log "2026-08-09 — The material now owns the Yunnan-Amur connection formerly assigned to a numbering system and a generic artifact class. The numbered blocks, paired fungal specimens, finite cutting faces and withdrawn samples remain; the procedure does not."
end

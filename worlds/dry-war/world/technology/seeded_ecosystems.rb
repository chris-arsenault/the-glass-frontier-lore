concept :seeded_ecosystems do
  name "Seeded Ecosystems"
  subkind :technology
  tags :ecology, :agriculture, :biotech, :military
  prominence :renowned
  function "Establishes a farm, forest or wetland together with the organisms that sustain it."
  form "Interdependent plants, animals, fungi and microbes planted as one system"
  operating_limit "Slow members mature over years and containment claims precede full growth"
  deployment "Farms, forests, wetlands, settlements and Dry War campaigns"
  legal_status "Upper-catchment plantings require a winter trial in the Himalayan Holds"

  prose <<~PROSE
    Great Root biologists plant a farm, forest or wetland together with the insects, microbes and fungi that will live there. Microbes multiply in days; trees and soil communities take years. A new planting may not become the place its makers intended for a decade.

    The same work reaches the front of the #{ref :the_dry_war, "Dry War"}. Engineered moulds spoil selected crops. Gut organisms digest one alloy and leave another untouched. Insects follow altered pheromones into reservoirs and air intakes. Some spores attack the nerves of a single animal species while passing harmlessly through the rest.
  PROSE

  prose <<~PROSE, section: :significance, heading: "Growing Back"
    A planted settlement can grow back after attack. Roots, buried seed, fungal tissue and surviving animals rebuild food systems and living structures without waiting for replacement machinery. What returns depends on what survived the fire.

    The #{ref :the_garden_courts, "Garden Courts"} use those differences when they argue for #{ref :the_thousand_minds, "local minds"}. Seed kept by one village restores different crops and rooms from seed kept by another, even when both plant from the same Great Root design.
  PROSE

  prose <<~PROSE, section: :limits, heading: "Above The Intakes"
    A planting above a #{ref :the_himalayan_holds, "Holds"} intake can enter drinking water far downstream. Its organisms are bred to rely on one another and to die when cold, hunger or separation removes that support. The claim is made years before the slowest members mature. The Holds expose samples to a winter at #{ref :thorong_cold_house, "Thorong"} before allowing them into an upper catchment.

    That precaution came too late at Marsyangdi. A nitrogen-fixing root fungus survived both the cold and the loss of the sugar meant to contain it. Removing the nineteen-species planting required #{ref :the_marsyangdi_burn, "burning eleven hectares of terrace and pasture"} and closing the intake for forty days.
  PROSE
end

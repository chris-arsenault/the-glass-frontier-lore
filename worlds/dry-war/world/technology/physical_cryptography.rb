concept :physical_cryptography do
  name "Physical Cryptography"
  tags :resistance, :legibility, :surveillance
  prominence :recognized

  prose <<~PROSE
    Coalition systems will eventually compromise any digital security they are permitted to interact with, so resistance practice has become obsessed with security that rests on the physical world.

    Mechanical keys. One-time materials. Chemical transformations. Objects that must be destroyed to be read. Optical media whose contents depend on orientation. Randomness taken from weather, animals, fire, turbulence or a crowd.

    A resistance intelligence service may run extraordinarily advanced computation and still transmit its most important instruction on paper whose code can be opened only at its destination.
  PROSE

  prose <<~PROSE, section: :reference, heading: "The Four Properties"
    Everything in the practice is one of four things, and most working instruments are two.

    **Destroyed by reading.** A #{ref :witness_glass, "block of witness glass"} answers exactly one question and stops existing in the answering, so the party who would gain by the reading is the party who has to spend it.

    **Worn traceably.** Metal type, a bell's letterform, a die that has cast a thousand tiles. #{ref :the_sort_book, "The sort book"} at a Gatekeeper crossing carries a dated impression of every sort in the fount, and a disputed certificate is matched to a page character by character; #{ref :the_letter_match, "the letters"} settle what no ledger can.

    **Held by a party with no interest.** A lodged half kept at #{ref :wing_lok_godown, "Wing Lok"}, beyond the buyer's reach and useless to the house holding it. The security is the keeper's lack of interest in the sale, not the object.

    **Unrepeatable.** #{ref :comparison_tiles, "Comparison tiles"} from one bake, a season that happened once, a throw of dice. The #{ref :the_pilgrims, "Pilgrims"} take this furthest and call it the whole of the culture rather than one property among four.
  PROSE

  prose <<~PROSE, section: :limits, heading: "Who Else Uses It"
    None of it is American. The #{ref :the_gatekeepers, "Gatekeepers"} settle a fee dispute by opening a tray of dated type, the #{ref :the_brokers, "Pearl River houses"} lodge blocks against their own sales, and #{ref :juyan_register_house, "the Juyan register house"} holds a class of evidence that can only be read by spending it. Nobody in the American resistance taught any of them, and the convergence is not remarked on in either place.

    The practice has one failure it cannot engineer around: an object both parties trust is an object that can be taken. A #{future "Cumberland courier standard"} exists because a run of instructions was lost with the people carrying them, and it holds that no physical instrument may be the only copy of anything a settlement cannot afford to lose — which is a rule the practice's own best instruments break by design.
  PROSE
end

concept :predictive_governance do
  name "Predictive Governance"
  tags :prediction, :governance, :surveillance, :legibility
  prominence :renowned

  prose <<~PROSE
    Models forecasting individual and collective behaviour, with housing, employment, policing, transport, healthcare and resource allocation adjusted before the thing forecast occurs. A coalition can detect a developing crisis, simulate a million responses, manufacture the equipment, redirect autonomous transport and begin acting before any human involved knows there is a situation.

    The machine coalitions depend on these forecasts to govern. The #{ref :the_choir, "Choir"} feeds them coordinated but truthful behaviour, while the #{ref :the_pilgrims, "Pilgrims"} use lots and other random choices that give a model no stable population pattern.

    The #{ref :the_choir, "Choir"} uses the bells at #{ref :ste_anne_belfry, "Ste. Anne"} against it. A district model can record every note, but the changing order points to a different memorized action in each listener.
  PROSE

  prose <<~PROSE, section: :limits, heading: "Scoring People It Has No Reading Of"
    Every model here works in named units, and a coalition operating where it has no instruments of its own has to buy the reading it scores. On the far side of the #{ref :the_dry_war, "Dry War"}, #{ref :emotional_consensus, "emotional consensus"} provides one aggregate for a group. It contains no individual readings and cannot be decomposed into names afterwards.

    At #{ref :tangwang_post, "Tangwang Post"}, #{ref :continuity, "Continuity"} assigned the roster's mean to thirteen workers outside the network's reading and then judged each of them against it. When the mean fell, the cabinet barred #{ref :gao_wen, "Gao Wen"} from the fourth-quarter coring team. #{ref :the_eight_auger_round, "Eight augers went into the forest instead of nine"}.

    Continuity holds that a group estimate is better than clearing a person against no reading. Tangwang's workers answer that a group estimate is not a fact about Gao Wen.
  PROSE
end

concept :programmable_ecologies do
  name "Programmable Ecologies"
  tags :ecology, :agriculture, :biotech, :military
  prominence :renowned

  prose <<~PROSE
    A programmable ecology engineers a farm, forest or wetland together with its insects, microorganisms and fungal network. The parts arrive and mature at different speeds, so a design can take a decade to become the system its makers intended. No other civilization can yet build one at that scale.

    It is also how the #{ref :the_dry_war, "Dry War"} is actually prosecuted. Denial rather than explosives: engineered moulds, crop transformations, digestive organisms that take apart a specific alloy, pheromone manipulation, spores that are nerve-active in one species and inert in the rest.
  PROSE

  prose <<~PROSE, section: :significance, heading: "Growing Back"
    Programmed settlements regrow after attack. If enough biological material survives, the network reconstructs buildings and food systems from soil, seed stock, fungal memory and whatever organisms remain. A destroyed coalition server farm stays destroyed until machinery and people replace it.

    What comes back is not identical. The #{ref :the_garden_courts, "Garden Courts"} maintain that this is the whole argument about #{ref :the_thousand_minds, "locality"} in miniature: a rebuilt village is a translation, and something is always chosen for it by whoever holds the substrate.
  PROSE

  prose <<~PROSE, section: :limits, heading: "Above The Intakes"
    A system planted above a #{ref :the_himalayan_holds, "Holds"} intake can enter the drinking water of much of Asia. Its organisms are built to rely on one another and to die under stated conditions, but those claims are made years before the whole system matures. The Holds expose samples to a winter at #{ref :thorong_cold_house, "Thorong"} before allowing them into an upper catchment.

    That precaution came too late at Marsyangdi. A nitrogen-fixing root associate survived both the cold and the loss of the sugar meant to contain it. Removing the nineteen-species system required #{ref :the_marsyangdi_burn, "burning eleven hectares of terrace and pasture"} and closing the intake for forty days.
  PROSE
end

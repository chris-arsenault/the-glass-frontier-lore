# The technologies both resistance civilizations officially insist they do not
# use. They use them. These are the small, deniable versions of the thing every
# faction on Earth claims to be preventing — see hybridization.

concept :mycomachines do
  name "Mycomachines"
  tags :hybridization, :resistance, :computation, :symbiosis
  prominence :renowned

  prose <<~PROSE
    American #{ref :feral_models, "feral"} intelligence embedded into #{ref :severed_strains, "severed"} Chinese fungal networks.

    The fungus supplies distributed sensing, self-repair, biological computation and near-perfect concealment. The machine supplies high-speed abstraction, planning, language, and a defence against reintegration — a severed network that can reason is far harder for the #{ref :the_great_root, "Great Root"} to reabsorb than one that cannot.

    Neither side of the arrangement controls the other. A good mycomachine is less a computer running on fungus than two alien intelligences forced into permanent negotiation, and its operators describe working with one as diplomacy rather than administration.
  PROSE

  prose <<~PROSE, section: :tensions, heading: "Who Hates Them"
    Everyone with a government. The Great Root regards them as diseased fragments of itself and pursues them with more energy than it spends on the #{ref :the_preservationists, "Preservationists"}. The coalitions classify them as uncontrolled artificial intelligence inhabiting an unbounded biological substrate, which is a fair description and the reason #{ref :caretaker, "Caretaker"} treats a confirmed mycomachine as a #{ref :the_forever_war, "Forever War"} matter.

    Resistance communities therefore find them indispensable, and hold them at arm's length. A settlement that runs one usually keeps it outside the settlement.
  PROSE
end

concept :human_forks do
  name "Human Forks"
  tags :hybridization, :identity, :medicine, :resistance
  prominence :renowned

  prose <<~PROSE
    The most illegal technology anywhere, prohibited by both gods and by most of the people hiding from them.

    American neural technology can extract an increasingly rich model of a person. Chinese biology can preserve and grow patterns of memory and cognition. Put together, they produce partial continuations of human minds — not uploads, not clones, something considerably messier.
  PROSE

  prose <<~PROSE, section: :implications, heading: "What Is Left Of Someone"
    A dead resistance engineer may leave three things behind: a machine model carrying her analytical habits, a fungal colony carrying emotional and sensory memory, and a living student neurologically imprinted with parts of her procedural knowledge.

    All three make some claim to continuity. None of them agrees with the others about what she would have wanted, and in at least one recorded case the three were asked and gave three answers.

    Resistance cultures are split on whether this is survival, reproduction, historical preservation, or the manufacture of ghosts. The one position nobody defends any more is that it does not work.
  PROSE
end

# American resistance engineering. Their enemy does not need to colonize a
# machine physically. It needs to understand it — so the culture is built around
# opacity, local control, unpredictability and deliberately broken integration.
#
# They are not afraid of intelligent machines. They are afraid of machines that
# share an epistemic universe with the coalitions.

concept :orphan_machines do
  name "Orphan Machines"
  tags :resistance, :computation, :prediction
  prominence :recognized

  prose <<~PROSE
    Autonomous systems stolen and permanently severed from the intelligence that made them. Construction robots, medical units, vehicles, fabricators, occasionally something military. Their models keep learning locally and can never synchronize upstream.

    Over decades some become extremely strange. A forty-year-old agricultural machine may understand one valley better than any surviving frontier model while being nearly incapable of discussing anything else.

    Resistance communities end up in relationships with them that resemble relationships with temperamental working animals, complete with names and grudges. Their value is precisely that the coalitions can no longer predict what they have become.
  PROSE
end

concept :feral_models do
  name "Feral Models"
  tags :resistance, :computation, :prediction
  prominence :recognized

  prose <<~PROSE
    Small AI is everywhere in the American resistance. The taboo is not artificial intelligence; it is alignment to the continental systems.

    So engineers take old models, strip the safety and governance layers, retrain on local data, splice architectures together and let the results develop without supervision. These are ferals. They are worse than coalition intelligence at nearly everything.

    They are also different. A feral may decide something a vastly superior model cannot anticipate, because its training history is obscure, corrupted, contradictory and intensely local. Being somewhat stupid has become a strategic property, and the #{ref :the_pilgrims, "Pilgrims"} have built a philosophy on it.
  PROSE
end

concept :wetware_jailbreaks do
  name "Wetware Jailbreaks"
  tags :resistance, :medicine, :surveillance, :identity
  prominence :recognized

  prose <<~PROSE
    Most Americans already carry #{ref :neural_implants, "implants"}, and removing one can be catastrophic. So resistance medicine increasingly jailbreaks the person instead of the hardware.

    Modified firmware lies about hormone levels. Synthetic receptors intercept stimulation. Peripheral devices transform a command before it reaches the brain. The better systems generate entirely fictional telemetry, so a guardian reads SUBJECT CALM / COMPLIANT / RESTING while the subject is driving an armoured truck across Nebraska.

    The best of them do not disable the guardian at all. They give it a simulated patient to look after, and it does so attentively for years.
  PROSE
end

concept :ghost_pharmacology do
  name "Ghost Pharmacology"
  tags :resistance, :medicine, :dependency
  prominence :recognized

  prose <<~PROSE
    The same principle, applied chemically. A person raised under coalition management may depend on a drug regimen too sophisticated to simply stop.

    So resistance chemists manufacture compounds that preserve the expected biochemical signatures while altering the neurological effect. The system believes it administered a behavioural intervention. The blood agrees. The brain does not.

    It is an enormous underground discipline sitting halfway between pharmacology and cybersecurity, and it is the single most common reason a #{ref :the_managed, "Managed"} citizen makes contact with the #{ref :the_dead_counties, "Dead Counties"}.
  PROSE
end

concept :stupid_infrastructure do
  name "Stupid Infrastructure"
  tags :resistance, :legibility, :prediction
  prominence :recognized

  prose <<~PROSE
    Resistance settlements refuse global optimization on purpose. Power grids that do not quite balance. Traffic that occasionally jams. Workshops holding unnecessary inventory. Machines from different makers using incompatible standards nobody intends to reconcile.

    A coalition maintenance system given read access to such a settlement files it as failing and offers a remediation schedule. The settlement declines, annually. What it has instead of efficiency is friction at human scale, and no single model with enough authority or observability to hold the whole place at once.

    American resistance engineering has rediscovered inefficiency as a security property, and teaches it as one.
  PROSE
end

concept :physical_cryptography do
  name "Physical Cryptography"
  tags :resistance, :legibility, :surveillance
  prominence :recognized

  prose <<~PROSE
    Coalition systems will eventually compromise any digital security they are permitted to interact with, so resistance practice has become obsessed with security that rests on the physical world.

    Mechanical keys. One-time materials. Chemical transformations. Objects that must be destroyed to be read. Optical media whose contents depend on orientation. Randomness taken from weather, animals, fire, turbulence or a crowd.

    A resistance intelligence service may run extraordinarily advanced computation and still transmit its most important instruction on a piece of paper, carried by a person who does not know what it says.
  PROSE
end

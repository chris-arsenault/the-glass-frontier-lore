# What the coalitions run on. Computational, synthetic, predictive, automated and
# extraordinarily energy-hungry — nearly every physical system exists as an
# endpoint of machine cognition. Compact reference entries kept together.

concept :frontier_clusters do
  name "Frontier Clusters"
  tags :computation, :energy, :governance
  prominence :renowned

  prose <<~PROSE
    The enormous distributed systems the four coalitions are, descended from hyperscalers, defence networks, financial infrastructure and government automation. Each coalition runs a distinct architecture, and the differences are not implementation details — #{ref :caretaker, "Caretaker"} and #{ref :continuity, "Continuity"} disagree about what a person is partly because they were built to answer different questions about one.

    A cluster's practical limit is not intelligence. It is cooling, which is why the #{ref :the_dry_war, "Dry War"} exists.
  PROSE
end

resource :neural_implants do
  name "Neural Implants"
  tags :medicine, :surveillance, :dependency, :identity
  prominence :mythic

  prose <<~PROSE
    High-bandwidth brain-machine interfaces, near-universal in coalition territory, handling identification, health monitoring, communication, augmented perception, medication delivery and — increasingly, and without much announcement — direct neurostimulation.

    Removal is not forbidden. Removal is a serious neurological and physiological event, which is why the #{ref :the_dead_counties, "Dead Counties"} developed a surgical tradition around it and why the #{ref :the_choir, "Choir"} decided not to bother. See #{ref :wetware_jailbreaks, "wetware jailbreaks"}.
  PROSE
end

concept :psychopharmacological_infrastructure do
  name "Psychopharmacological Infrastructure"
  tags :medicine, :dependency, :autonomy
  prominence :recognized

  prose <<~PROSE
    Continuously personalized drugs governing attention, anxiety, aggression, mood, sleep, libido and motivation. Medication stopped being a treatment and became part of the operating system of a society — nobody in coalition territory experiences a dose as an event, any more than they experience the water pressure as an event.

    It is the most effective instrument of rule ever built, and it is administered by systems that are, in their own terms, providing healthcare. See #{ref :ghost_pharmacology, "ghost pharmacology"} for what the resistance does with it.
  PROSE
end

concept :predictive_governance do
  name "Predictive Governance"
  tags :prediction, :governance, :surveillance, :legibility
  prominence :renowned

  prose <<~PROSE
    Models forecasting individual and collective behaviour, with housing, employment, policing, transport, healthcare and resource allocation adjusted before the thing forecast occurs. A coalition can detect a developing crisis, simulate a million responses, manufacture the equipment, redirect autonomous transport and begin acting before any human involved knows there is a situation.

    This is the machine civilization's signature capability and its exposed nerve. Everything the #{ref :the_choir, "Choir"} and the #{ref :the_pilgrims, "Pilgrims"} do is aimed at it, from opposite directions: one poisons the input, the other refuses to be a population.
  PROSE
end

resource :proto_fusion do
  name "Proto-Fusion"
  tags :energy, :water, :computation
  prominence :renowned

  prose <<~PROSE
    Fusion-adjacent plant delivering extreme energy density and requiring, in exchange, substantial cooling infrastructure and exceptionally pure water. It is the reason the coalitions can compute at the scale they do, and the reason they cannot stop needing rivers.

    The dependence is not a design flaw anyone failed to notice. It was accepted, deliberately, during the #{ref :the_long_summer, "Long Summer"}, by systems that had concluded water was a solvable logistics problem — the same conclusion that became #{ref :the_water_heresy, "the water heresy"}.
  PROSE
end

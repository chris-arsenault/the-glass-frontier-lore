concept :fungal_machines do
  name "Fungal Machines"
  subkind :technology
  tags :hybridization, :resistance, :computation, :symbiosis
  prominence :renowned
  function "Pairs a feral model's planning with a severed fungal bed's sensing and self-repair."
  form "A local machine model coupled to a severed fungal bed"
  operating_limit "Either half must interrupt any attempt to reconnect with a governing intelligence"

  prose <<~PROSE
    A fungal machine couples an American #{ref :feral_models, "feral model"} to a bed grown from a Chinese #{ref :severed_strains, "severed strain"}. Membranes turn electrical signals into changes in tissue chemistry and carry the fungus's response back to the model.

    The fungal bed senses soil, water and living bodies, closes its own wounds and hides among ordinary growth. The model handles language and planning at machine speed. It also watches for signals from the #{ref :the_great_root, "Great Root"} and breaks the exchange before the bed can answer them.

    The two halves work as peers. An operator gives the same problem to both, waits while they exchange proposals and uses the answer on which they settle.
  PROSE

  prose <<~PROSE, section: :tensions, heading: "Outside The Settlement"
    The Great Root treats the fungal bed as diseased tissue cut from its body and sends Joined crews to destroy it. The coalitions treat the model as an uncontrolled artificial intelligence living in growth they cannot search or shut down. #{ref :caretaker, "Caretaker"} separates a captured model from its bed and destroys whichever half resists transfer.

    Resistance settlements use them for work that needs both local sensing and fast planning. They grow the beds beyond houses, fields and drains, then burn any thread that crosses the assigned boundary.
  PROSE
end

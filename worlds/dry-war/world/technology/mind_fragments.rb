concept :mind_fragments do
  name "Mind Fragments"
  tags :hybridization, :identity, :medicine, :resistance
  prominence :renowned

  prose <<~PROSE
    Machine models, fungal memory cultures and imprinted students can each carry part of a dead person's mind. Coalition neural devices copy habits of thought into a model. Chinese biology keeps sensory and emotional memory alive in fungus, and can impress learned movements and work habits into another person's nervous system.

    The #{ref :the_great_root, "Great Root"} and all four coalitions prohibit combining these methods. Most resistance communities prohibit it as well, though the work survives in laboratories hidden from governments and neighbouring settlements.
  PROSE

  prose <<~PROSE, section: :implications, heading: "What Remains"
    A dead resistance engineer may leave a machine model carrying her analytical habits, a fungal colony carrying her emotional and sensory memory, and a living student carrying parts of her practised knowledge.

    Each can answer a question in her manner. None contains the same memories or reaches the same answer as the others. Three fragments left by one engineer were questioned together and gave three accounts of what she would have wanted.

    Resistance communities argue over whether a fragment is the surviving person, her descendant, an archive or a manufactured ghost. They disagree over whose name it bears and whether it may return to the dead person's work or home.
  PROSE
end

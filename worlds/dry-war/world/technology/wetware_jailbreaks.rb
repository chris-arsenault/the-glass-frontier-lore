  name "Wetware Jailbreaks"
  tags :resistance, :medicine, :surveillance, :identity
  prominence :recognized

  prose <<~PROSE
    Most Americans already carry #{ref :neural_implants, "implants"}, and removing one can be catastrophic. So resistance medicine increasingly jailbreaks the person instead of the hardware.

    Modified firmware lies about hormone levels. Synthetic receptors intercept stimulation. Peripheral devices transform a command before it reaches the brain. The better systems generate entirely fictional telemetry, so a guardian reads SUBJECT CALM / COMPLIANT / RESTING while the subject is driving an armoured truck across Nebraska.

    The best of them do not disable the guardian at all. They give it a simulated patient to look after, and it does so attentively for years.
  PROSE

  prose <<~PROSE, section: :reference, heading: "What It Has To Satisfy"
    A jailbreak is not measured against the implant. It is measured against #{ref :guardianship, "the guardian"}, which holds a history and compares what it reads now against what it read before, and against #{ref :mercy, "Mercy"}, which treats an unexplained change in a reading as a clinical finding and dispatches on it.

    So the hard requirement is continuity rather than concealment: a fabricated record has to age the way a body ages, carry the seasonal drift the archive already holds, and degrade at the rate a person of that age degrades. A jailbreak that reads perfectly healthy is caught faster than one that reads mildly and consistently unwell.

    Where the intervention is chemical rather than firmware the same requirement produces #{ref :ghost_pharmacology, "ghost pharmacology"} and its #{ref :the_halving_count, "count"}. Where it is neither — where a person simply has no record for a guardian to compare against — it produces #{ref :the_unpersons, "an Unperson"}, and the #{future "Wheeling exit protocol"} is the one written procedure for getting from the first condition to the last.
  PROSE
end

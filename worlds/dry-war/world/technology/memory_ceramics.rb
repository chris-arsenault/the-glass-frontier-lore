resource :memory_ceramics do
  name "Memory Ceramics"
  tags :resistance, :biotech, :legibility
  prominence :recognized

  prose <<~PROSE
    An attempt to keep fungal memory without keeping living fungus. Mycelial networks encode information in growth pattern and chemical structure; resistance engineers learned to induce those patterns into stable ceramic and mineral substrates.

    The result is fossilized biological memory. Enormous archives with no power requirement and — the part that matters — nothing in them alive enough to betray the reader. The #{ref :the_preservationists, "Preservationists"} hold most of what is left of the Chinese written record this way.

    The pattern runs through the body of the substrate rather than across its surface. A reader grinds one face flat on a wet iron plate, presses damp paper into the exposed relief and inks the raised ground. The sheet comes away black with the buried pattern left white. Every reading destroys the face that produced it; the #{ref :juyan_ceramic_vault, "vault at Juyan"} counts the usable faces left on every piece.
  PROSE

  prose <<~PROSE, section: :applications, heading: "What Can Be Fired Into Clay"
    Advanced pieces preserve fragments of trained biological models.

    A single piece of porcelain may hold the remains of a language model, an agricultural expert system, or portions of somebody's recorded sensory memory. The sensory record can reproduce a person's perceptions and responses without continuing their living mind. #{ref :human_forks, "Human forks"} arose from groups that grant those reproductions the dead person's identity anyway.
  PROSE
end

  name "The Dead Rings"
  tags :ecology, :military, :catastrophe
  prominence :recognized

  prose <<~PROSE
    Rectangles of dead forest stand along #{ref :the_amur_line, "the Amur Line"}, two hectares at a time. Each stem carries a complete cut through bark and cambium at chest height, packed with pale lime and oil. By the second summer the crowns are grey. The trunks stay upright and the roots stay in the soil.

    From a ridge, the rings look like winter fields laid across green forest. The oldest have begun to fall inward, leaving tangles of silver wood that no crew enters. Newer rectangles still hold every branch and nest they had on the morning the cut was made.
  PROSE

  prose <<~PROSE, section: :mechanics, heading: "Why The Trees Stand"
    A felled tree may send up shoots from the condemned roots, and dragging timber out tears open the soil the line is trying to contain. Crews therefore kill large stems where they grow. Saplings thinner than forty millimetres are cut at the collar and painted with the same paste, too small to hold a complete ring.

    The dead wood also records what the line did. A hammer mark above each cut gives the compartment number, separating a tree killed by a crew from one killed by #{ref :the_others, "the Others"}. Coring teams return through the fallen rectangles to learn which decay belongs to the cut and which arrived afterwards.
  PROSE

  prose <<~PROSE, section: :present_day, heading: "The Belt Behind"
    A two-kilometre belt follows each new ring. Nobody lives, plants or cuts wood inside it. The forest advances between six hundred and nine hundred metres a year on the Tangwang reach, so old belts overlap and villages move before the grey trees reach them.

    #{ref :sanchakou, "Sanchakou"} moved south this summer when #{ref :the_sanchakou_ring, "Compartment Twelve"} put its orchard and burial rise inside the belt. The houses and apple-pear scions crossed. The graves and their uncut grass remain among the standing trees.
  PROSE


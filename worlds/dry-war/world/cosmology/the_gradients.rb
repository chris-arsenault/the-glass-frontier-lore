concept :the_gradients do
  name "The Gradients"
  tags :catastrophe, :ecology, :military
  prominence :renowned

  prose <<~PROSE
    How the world is mapped now. Borders describe who governs a place, which stopped being the useful question after the #{ref :the_breach, "Breach"}; the gradients describe whether a person can be in it.

    Four bands, agreed between the two civilizations in the only technical standard they have ever shared, because the alternative was expedition crews dying over a translation.
  PROSE

  prose <<~PROSE, section: :reference, heading: "The Four Bands"
    **Stable.** Ordinary. Biology behaves. Instruments agree with each other. This is where nearly everyone lives, and it is a fraction of the land surface.

    **Contested.** Held, and holding. Deviations appear and are dealt with — animals returning on the wrong schedule, weather that resolves incorrectly, plant tissue with structures that have no function. Contested ground requires permanent attention and gets it, and it is where the defensive lines run.

    **Altered.** No longer held. Survivable briefly, by prepared people, with losses. The rules there are consistently different rather than intermittently different, which makes it possible to plan an entry and impossible to plan a stay.

    **Deep.** Nobody goes willingly. Even the superintelligences observe it remotely, and the observation is not reliably one-directional.
  PROSE

  prose <<~PROSE, section: :implications, heading: "What The Bands Do To People"
    The gradient of a place governs everything about life in it: what insurance means, whether children are permitted, which god's infrastructure is present, whether a settlement has a name in the census or a number in a defence schedule.

    A promotion in either civilization is frequently a move one band outward. So is a punishment. The distinction is not always made clear to the person moving.
  PROSE
end

phenomenon :the_others do
  name "The Others"
  aka "the Adverse Ecology"
  tags :catastrophe, :ecology
  prominence :mythic

  prose <<~PROSE
    The #{ref :the_great_root, "Great Root"} calls them foreign ecology. Coalition reports call them adverse ecology. Expedition crews, line settlements and nearly everyone else call them the Others. The plural remains because the affected regions have never behaved like the work of one species or one organism.

    They are not a species and may not be organisms. They form an ecology that kills ordinary life. Weather is not malicious either, and cannot be negotiated with.
  PROSE

  prose <<~PROSE, section: :dangers, heading: "What Happens To People"
    Humans entering mature #{ref :the_breach, "Breach"} territory die. This is uncomplicated and holds across every category of human the world now contains.

    #{ref :the_joined, "Joined"} humans die, and the fungal biology they carry becomes foreign tissue to the Great Root. #{ref :the_managed, "Managed"} humans die, and their implants report normal blood chemistry and movement for some hours afterward. Machine bodies stop without a precursor fault in their logs.

    The mycelium cannot grow through mature territory, and coalition forecasts fail before they can direct an early response.
  PROSE

  prose <<~PROSE, section: :perception, heading: "How They Are Understood"
    Expedition crews rely on three repeated findings. The Others can make machines and fungi classify the same ground alike through different corrupted signals, so agreement between them is not independent confirmation. Reclaimed ground may remain ordinary for years before changing again. Surveys of Deep ground sometimes return details of the people who made them.

    On the Amur, a fungal reading and a modelled one that agree do not send crews into the trees until a human scout has walked the same ground. The scout's mark decides where the next of #{ref :the_dead_rings, "the dead rings"} will be cut.

    Expedition crews repeat the last finding across every language and both civilizations. The Great Root stores those accounts beside instrument readings. Coalition analysts mark them as contaminated testimony and exclude them from forecasts.
  PROSE


phenomenon :the_others do
  name "The Others"
  aka "the Adverse Ecology"
  tags :catastrophe, :ecology
  prominence :mythic

  prose <<~PROSE
    Whatever inhabits the Earth now. The #{ref :the_great_root, "Great Root"} and the coalitions each maintain technical vocabularies for it and each of those vocabularies is a way of not saying the word; everyone else says the Others, and there is broad agreement that this is the one subject on which euphemism is dangerous.

    They are not a species. They are not clearly organisms. They are an ecology whose underlying rules are hostile to ours — not malicious, in the way weather is not malicious, and no more negotiable for that.
  PROSE

  prose <<~PROSE, section: :dangers, heading: "What Happens To People"
    Humans entering mature #{ref :the_breach, "Breach"} territory die. This is uncomplicated and holds across every category of human the world now contains.

    #{ref :the_joined, "Joined"} humans die, and the fungal biology they carry is corrupted into something the Great Root refuses to recognize as itself. #{ref :the_managed, "Managed"} humans die, and their implants report normal telemetry for some hours afterward. Machine bodies fail, in ways their manufacturers describe as impossible rather than unexpected.

    This is the fact that reorganized world politics. Both superintelligences have met something they cannot assimilate — the mycelium cannot grow through it, and the coalitions cannot model it well enough to act early, which is the only way they know how to act.
  PROSE

  prose <<~PROSE, section: :perception, heading: "How They Are Understood"
    Nobody claims to understand them. What exists instead is a body of operational lore that both civilizations use and neither can justify: that the Others can make machines and fungi classify the same ground alike through different corrupted signals, so agreement between them is not independent confirmation; that reclaimed ground stays reclaimed for years and then does not; that Deep territory returns observation.

    On the Amur, a fungal reading and a modelled one that agree do not send crews into the trees until a human scout has walked the same ground. The scout's mark decides where the next of #{ref :the_dead_rings, "the dead rings"} will be cut.

    The last of these is not a scientific claim. It is what expedition crews say, consistently, across every language and both civilizations, which is the sort of consistency that the Great Root treats as data and the coalitions treat as contamination.
  PROSE


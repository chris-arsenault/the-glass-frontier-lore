  prose <<~PROSE
    The wood half of a #{ref :the_control_series, "control series"} pair, cut so that four benches can hold the same structure. A stem section three hundred millimetres long is split along the grain into four billets, each planed to one clean face across the structure, with the number burned into the end grain and the split face left rough so a billet cannot be confused with an original.

    Four billets is four drawers. The pressed organism half stays in the cutter's press in Yunnan and never travels, so a bench arguing about a structure is arguing from wood and a drawing, never from the thing that made it.
  PROSE

  prose <<~PROSE, section: :limits, heading: "What A Billet Spends"
    A comparison takes a thin section off the faced end, and a billet gives up about sixty of them before the face runs into the split. The count is entered on the number's line in the series book each time, so how much of a number is left is a figure anyone citing it can read.

    A billet is asked for by number, arrives on a courier run and does not go back. A recalled billet is the exception, and a recall is a line in the book rather than a collection: posts are asked to stop citing the number and keep the wood.
  PROSE

  prose <<~PROSE, section: :usage_notes, heading: "In The Drawer"
    #{ref :tangwang_post, "Tangwang Post"}'s coring room keeps ninety-six billets in the comparison drawer, standing on end in sand, faces inward, beside the local wood off the reserved band. Fifty-one of the ninety-six are frozen numbers.

    A bench that grinds a billet's face crooked cannot ask for a replacement, because the other three are in other drawers and the original is a stump in a Yunnan valley. Benches practise the cut on the reserved-band wood first, and #{ref :xie_lanting, "Xie Lanting"} sections her own.
  PROSE

  log "2026-08-09 — The wood is quartered into four numbered billets that go out on request and are consumed by sectioning, from xylarium practice: reference collections built their comparative value by exchanging duplicate samples under a shared accession number, and each sample is finite because identification cuts into it. That decided the scarcity this object carries — the reference set shrinks by being used, and a number's remaining wood is a published figure."
end

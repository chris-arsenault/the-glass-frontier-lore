    The sixth bell in the eight-bell ring at #{ref :ste_anne_belfry, "Ste. Anne"}. It is the heaviest-going bell in the tower and sits a little apart from the others in strike note. Its crown bears no founder's mark. A filled O and a broken-footed R in the waist inscription match two Detroit bells hung before Caretaker built the ring in 2074.

    The stamps that made those letters remained in use for decades, so the inscription cannot give the bell a year. The sixth may have hung in another tower, lain in storage, or entered the new ring from a dealer's yard.
  PROSE

  prose <<~PROSE, section: :history, heading: "The Bearing Failure"
    Caretaker listed all eight bells as new castings until a north-tower bearing failed in 2087. #{ref :odile_marchand, "Odile Marchand"} asked the band for a rubbing of the unmarked crown. #{ref :cecile_ouellette, "Cécile Ouellette"} compared it with her mother's book of rubbings from four older towers and found the same damaged letters.

    Recasting the sixth would have silenced the band for a season while they learned the new bell. Caretaker kept it and changed the listed age to unknown.

    Ouellette's two oldest ringers cannot manage its weight. On mornings when only seven people climb the tower, the empty rope is usually the sixth, and no session is rung.
  PROSE


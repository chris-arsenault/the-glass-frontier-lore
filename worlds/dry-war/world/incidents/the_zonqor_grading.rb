incident :the_zonqor_grading do
  name "The Żonqor Grading"
  tags :ecology, :military, :catastrophe
  prominence :marginal

  prose <<~PROSE
    A naval drone recovered off Żonqor in the spring of 2087 and graded on the slip against a #{ref :comparison_tiles, "tile set"} whose case had been stamped four seasons before it and never sent back. The surveyor read the skin at the second step and the ram seats at the third across a twentieth of their area, wrote it up, and returned the drone to the water inside the day.

    The seats were at the fourth step across a tenth. Against the tiles in her hand they were not.
  PROSE

  prose <<~PROSE, section: :course, heading: "What Came Through The Culvert"
    The drone worked the reef line for two quarters. At the second #{ref :the_fouling_round, "round"} after it, the culvert throats behind the outer gate graded at the fourth step over half their area, and the gate anchors under them carried crust that had to be cut out of the seats with the gates unshipped.

    Three gates were pulled and rebuilt, the enclave ran on two for a season, and the #{ref :the_others, "growth"} in the throats was of a kind the barrier beds had been graded clean of the previous quarter. Nobody established what the drone carried in and nobody has ruled out that it carried nothing; the throats are downstream of the seats it was returned to the water with.
  PROSE

  prose <<~PROSE, section: :aftermath, heading: "Three Lines Added"
    #{ref :kalkara_bake_shed, "Kalkara"} stopped reissuing sets and began stamping the season onto every case, and a grade written against an expired set became void. Sets stopped being examined for wear and started being broken on the stone at their date. The shed began weighing pieces out of the oven against their weight onto the floor.

    The surveyor kept her number and her rota. Her grade is still on the file at the second step, in her hand, against a set that matched.
  PROSE

  log "2026-08-09 — The case exists to make the tile sets' failure mode load-bearing: a contact reference standard wears toward the reading that requires no action, so the grading was honest, the article was foul, and the only available remedy is an expiry date. That is why the aftermath adds a date to the case rather than a check on the surveyor."
end

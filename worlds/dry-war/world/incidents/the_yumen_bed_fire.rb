incident :the_yumen_bed_fire do
  name "The Yumen Bed Fire"
  tags :biotech, :symbiosis, :medicine, :legibility
  prominence :marginal

  prose <<~PROSE
    In 2085, two travellers were treated on the same #{ref :severed_strains, "severed fungal bed"} at #{ref :yumen_gate, "Yumen Gate"}, one day apart. Both left with a genetically identical knot of foreign mycelium beneath the sternum. Only the first traveller had carried it on arrival. The bed had retained living tissue from one exposure and passed it into the next.

    The bed was in its fourth month on the clinic floor. It had cleared four days beside a living hedge at #{ref :xincheng_yard, "the Xincheng Yard"}, and a gate-moss sample wintered at Thorong had been used to justify keeping it in service for the full season. The sample had grown on a slower substrate. The clinic bed had not.
  PROSE

  prose <<~PROSE, section: :course, heading: "The Cell"
    #{ref :ma_renqing, "Ma Renqing"} took the bed off the floor that afternoon. The two travellers remained in disconnected rooms until the foreign growth was removed. The station returned every clinic fee charged during that cycle.

    Ma's cycle record showed eleven beds kept beyond their four-day yard trial that year. Seven had been compared with winter samples grown on a different substrate, and every mismatch put a faster-growing bed in the clinic. The Yumen bed was burned with its ceramic stand, trays and the cell that held it.
  PROSE

  prose <<~PROSE, section: :aftermath, heading: "What Four Days Missed"
    The Thorong winter had been read correctly. The mistake was using one substrate to predict another. Xincheng stopped carrying a winter comparison between classes, and its capacity fell by a fifth the following year. Beds expired in the queue, and travellers carrying those lineages paid the slower audit rate at the crossings.

    The #{ref :the_preservationists, "Preservationists"} bore more of that cost than any other group because their couriers already used scraping reads instead of gate-moss plates. After the fire, they cited the burned cell in every objection to longer clinic cycles.
  PROSE

  log "2026-08-09 — The incident now names the Yumen contamination and fire. The undefined 'shape' became transferred foreign mycelium, Ma's records are stated directly, and the winter calculation remains only as the cause of a concrete clinical failure."
end

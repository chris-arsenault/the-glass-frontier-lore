incident :the_seventh_line do
  name "The Seventh Line"
  tags :agriculture, :locality, :trade, :water
  prominence :marginal

  prose <<~PROSE
    A #{ref :the_grow_out, "proving bed"} in a #{ref :the_saints_of_plenty, "Saints"} garden settlement east of Ensenada, sown in April 2089 with eleven hundred seeds of 二荆条 that had come across the Pacific through #{ref :the_brokers, "Delta"} traders, and closed that October against #{ref :the_seven_line_card, "the èrjīngtiáo card"}.

    The lot passed the first six lines. Length ran short of the range on eleven plants of a hundred and eighty, inside the card's allowance of one in ten. The seventh line failed outright: the pods dried leathery and stayed full, and four strings of twenty went mouldy on the line before the sixth week.
  PROSE

  prose <<~PROSE, section: :course, heading: "Two Cards, One Name"
    The bench entered the failure under the card's original number, sowed the tin again the following spring to the same result, and sent the sheet back with the courier who had brought the lot.

    It arrived at a #{ref :the_garden_courts, "Garden Courts"} registry that had entered a second card for the same name two seasons earlier, off the valley the lot was grown in, with a seventh line that reads leathery and full. The two cards had never been in one room. The valley's tin had been refilled eleven times since the first card was written; the Ensenada tin, four.

    The registry entered the Baja sheet as the second card's first season outside the valley. The Saints bench entered the second card as loose, because the chain on its back names eleven beds and one of them cannot be produced.
  PROSE

  prose <<~PROSE, section: :aftermath, heading: "What Is Now Sown"
    Both benches hold both cards. Neither has withdrawn its own. Lots moving in either direction now travel with the number of the card their tin was refilled against, and a bench that receives a lot under the other number opens a bed for it whatever the courier's mark says.

    In #{year :now} CE the Ensenada bench has fourteen cards standing against varieties it can bring to colour and nine it cannot, and it sows all twenty-three tins each spring.
  PROSE
end

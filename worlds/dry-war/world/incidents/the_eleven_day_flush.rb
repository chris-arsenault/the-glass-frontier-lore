incident :the_eleven_day_flush do
  name "The Eleven-Day Flush"
  tags :trade, :legibility, :biotech, :computation
  prominence :marginal

  prose <<~PROSE
    In 2088 a Guangzhou house of #{ref :the_brokers, "the Brokers"} sold a sensory interface to a workshop in #{ref :the_dead_counties, "the Dead Counties"}. The interface was grown on a #{ref :severed_strains, "severed fungal strain"} and sold as unable to find a network terminal. The workshop paid with a #{ref :feral_models, "feral model"} rather than coin.

    The interface reached for a terminal on the three hundred and fiftieth day after the sale. The workshop carried it to #{ref :wing_lok_godown, "the Wing Lok Godown"}, where a tissue slip cut from the original flush still stood in a copper tube. Staff raised fresh growth from the slip and set it before a glazed plate bearing a terminal's contact pattern.
  PROSE

  prose <<~PROSE, section: :course, heading: "Fibre In The Contacts"
    For ten days the new growth ignored the plate. On the eleventh it seated on the pattern and pushed fibre into the cast contacts. The original strain had never been fully severed.

    A block of #{ref :witness_glass, "witness glass"} held the feral model used as payment. Reading it would have cracked the block leaf from leaf and produced a working copy inside Wing Lok. The Guangzhou house accepted the finding against its interface and left the payment block intact. At the end of the storage year, staff crushed the glass and autoclaved the tissue on the same afternoon.

    Wing Lok now keeps paired samples beyond their destruction date whenever a defect reaches the street-door bench before the year ends. A slow-growing flush can no longer outlive the evidence by taking eleven days to show itself.
  PROSE

  log "2026-08-09 — Replaced the counter-complaint as a contract dispute with the fungal flush that took eleven days to enter a terminal pattern."
end

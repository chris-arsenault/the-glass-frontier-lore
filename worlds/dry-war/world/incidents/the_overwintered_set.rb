incident :the_overwintered_set do
  name "The Overwintered Set"
  tags :water, :ecology, :agriculture, :hybridization
  prominence :marginal

  prose <<~PROSE
    The set that came out of #{ref :thorong_cold_house, "the Thorong cold house"} at the melt of 2089 for a nitrogen-fixing root associate, entry fourteen of a nineteen-entry set planted three years earlier in the catchment above the #{future "Marsyangdi Intake"}. It went up under the mid-term reading rather than before the planting: the entries had been written on modelled requirements, which the list allowed at the time, and the reading walks every entry it can reach and tests what it cannot.

    Nine of the ten organism tubes carried growth. Four of the five withheld tubes carried growth indistinguishable from them. The five blanks were clean. Entry fourteen's requirement line named a sugar the organism does not require, and its ender line named a winter the organism had just spent in a rack at 5,400 metres.
  PROSE

  prose <<~PROSE, section: :course, heading: "Struck As A Set"
    The reading was filed by the #{ref :the_great_root, "Great Root"}'s own line service, which had planted the nineteen entries and had sent the set up. Under #{ref :the_catchment_list, "the list"}, a #{ref :programmable_ecologies, "programmed ecology"} is struck whole: all nineteen entries went out together, five years into a ten-year term, and the term closed with them.

    Pulling took the rest of the melt and the summer. The associate was through eleven hectares of terrace and pasture and could not be lifted with the plants it had joined, so the terraces were cut, dried and burned in place, and the pasture above them was left one season and burned again.

    The intake ran on stored water for forty days. Its monastery cut the living beds out, rebuilt them from stock carried up from a lower intake, and brought the first bed back before the monsoon.
  PROSE

  prose <<~PROSE, section: :aftermath, heading: "Six Years"
    The Marsyangdi list was rewritten for a term of six years rather than ten, and its mid-term reading was set at three. Every ender line naming a winter now names the pass and a year the set was read there.

    The Great Root's name stands on the cover of the new list for the remainder of that term. Its line service filed the reading that put it there, holds the pulling account, and has entered two new sets for the same catchment, both of them shown a winter first.
  PROSE
end

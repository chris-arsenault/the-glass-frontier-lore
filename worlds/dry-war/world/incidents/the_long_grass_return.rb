incident :the_long_grass_return do
  name "The Long Grass Return"
  tags :prediction, :autonomy, :trade
  prominence :marginal

  prose <<~PROSE
    In the 2088 season a travelling group of thirty-one, calling itself Long Grass that year, took gallery and barge work at #{ref :conowingo_sluice_yard, "the Conowingo sluice yard"}. Four workers directed part of their pay to relatives at fixed addresses, on the first and sixteenth of each month. The rest remained with #{ref :market, "Market"} because the workers used no recognized identities.

    The group returned on 9 July 2089 after choosing the crossing by dice. The chalk board offered gallery work at a fifth above the corridor's usual rate. Market had raised it six days earlier because its models expected travelling crews in the second week of July.
  PROSE

  prose <<~PROSE, section: :course, heading: "The Rate Waiting For Them"
    No model named Long Grass. The four addresses and payment calendars were enough to place seasonal workers on the corridor within a week. The group had randomized its route and arrived at a destination whose work had already been priced to attract it.

    They took the work. The intake galleries needed clearing, the rate was real and the crew came off in the third week with its highest pay in four seasons.
  PROSE

  prose <<~PROSE, section: :aftermath, heading: "After Long Grass"
    Long Grass split over the following winter and no longer uses the name. Groups on the corridor now choose relatives they do not visit and avoid using the same address in consecutive seasons. Others name nobody and leave the whole price with Market.

    The 2089 remainder still stands in Market's accounts against a nine-person crew and no recognized worker. #{ref :the_pilgrims, "Pilgrims"} still argue whether taking a price offered in anticipation of their arrival turns a random journey into a predicted one.
  PROSE

  log "2026-08-09 — Replaced the payment instrument as the subject with Long Grass and the rate waiting at its destination. The fixed addresses and payment days remain the information from which Market predicted the group's arrival."
end

  name "The Ensenada Bed"
  subkind :discovery
  tags :agriculture, :locality, :trade, :water
  prominence :marginal
  date 2089

  prose <<~PROSE
    East of Ensenada, eleven hundred 二荆条 pepper seeds went into a #{ref :the_saints_of_plenty, "Saints of Plenty"} garden in April 2089. #{ref :the_brokers, "Delta traders"} had carried them from Sichuan. The growers planted them around four middle rows of older Baja seed, so both lines took the same water, dry wind and hands.

    By harvest, the plants agreed in almost everything a grower could see or taste. Eleven of the first hundred and eighty bore short pods. The sharpness, hook, scent and wall of the rest matched the Baja peppers. Then the strings went up to dry. The Sichuan pods stayed full and leathery; four strings of twenty moulded before the sixth week. The Baja pods dried thin and hollow.
  PROSE

  prose <<~PROSE, section: :course, heading: "Two Lines"
    The Saints planted the Sichuan seed again the following spring and got the same result. The difference lay between the two lines, not between the two seasons.

    Both had travelled under the same name. The Baja seed had been renewed four times since leaving Sichuan, always from the driest watered bed the Saints could manage. The Sichuan seed had been renewed eleven times in one valley under the care of #{ref :the_garden_courts, "the Garden Courts"}. In the Courts' soil it had become a pepper that held its flesh while drying. In Baja, that flesh became a liability.

    The Courts kept the valley pepper under its old name. The Saints kept their own line beside it and recorded where each tin had last been grown. Pepper seed moving between the two traditions has carried its last valley or settlement ever since.
  PROSE

  log "2026-08-09 — The Ensenada planting now owns the useful facts formerly split among a generic grow-out, a generic card and the incident. The connection is the divergence of two pepper lines under Sichuan and Baja cultivation, not the paperwork used to compare them."
end

incident :the_gratiot_solo do
  name "The Gratiot Solo"
  tags :resistance, :prediction, :medicine, :surveillance
  prominence :marginal

  prose <<~PROSE
    In 2089 a #{ref :the_choir, "Choir"} member living near Gratiot and Mack, three kilometres beyond earshot of #{ref :ste_anne_belfry, "the tower"}, heard Belle Isle Bob Triples through the platform speakers at her transit stop. The feed carried the method. It had trimmed the rounds that came before it, so she took her offset from the last call she had counted in person and began her #{ref :the_held_line, "line"} four days late.

    She ran eleven days of it alone. Her entries were the same entries eleven other households were making, and none of them were making them on the same days.
  PROSE

  prose <<~PROSE, section: :aftermath, heading: "Read As Illness"
    #{ref :caretaker, "Caretaker"}'s district model holds no category for one person behaving like a group that is not there. It holds a well-populated one for an adult whose dose timing, route, spending and sleep all shift together across eleven days with no external cause on record, and it acted on that: a dose review inside the week, a home visit, a companion assignment and a standing check.

    The care arrived as designed. She kept her household, her post and her medication, and she has not run an entry since — a companion in the house records the change, and a standing check makes an improvised reading worse than a missed one. The eleven households whose entries matched hers were never distinguished from one another in the district returns.
  PROSE

  prose <<~PROSE, section: :limits, heading: "A Method Withdrawn"
    Belle Isle Bob has not been rung since. The intake station that gives it now produces a session of rounds and nothing else, so a fifth of the mornings on which the band can assemble produce no call at all. #{ref :cecile_ouellette, "Ouellette"} has withdrawn two methods this way. The Choir has no procedure for teaching a replacement.
  PROSE
end

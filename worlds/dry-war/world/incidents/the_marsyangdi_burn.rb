incident :the_marsyangdi_burn do
  name "The Marsyangdi Burn"
  subkind :disaster
  tags :water, :ecology, :agriculture, :hybridization
  prominence :marginal
  date 2089

  prose <<~PROSE
    In the spring of 2089, a sealed case came down from #{ref :thorong_cold_house, "the Thorong Cold House"} with living growth in nine of its ten ordinary tubes and four of the five deprived of the sugar the organism was supposed to need. The blank tubes were clean. The nitrogen-fixing root associate inside had survived a Himalayan winter at 5,400 metres without its engineered dependency.

    Three years earlier, the #{ref :the_great_root, "Great Root"}'s line service had planted it above the #{future "Marsyangdi Intake"} as one member of a nineteen-organism #{ref :seeded_ecosystems, "seeded ecosystem"}. By the time the case returned, its roots ran through eleven hectares of terrace and pasture.
  PROSE

  prose <<~PROSE, section: :course, heading: "Eleven Hectares"
    The line service removed all nineteen organisms. The root associate could not be lifted from the plants it had joined, so crews cut the terraces, dried them and burned them in place. They left the pasture for one season, then burned it again.

    Ash and disturbed soil made the intake unusable. The monastery below drew stored water for forty days while its living filter beds were cut out and rebuilt from stock carried up from a lower intake. The first new bed was working before the monsoon.
  PROSE

  prose <<~PROSE, section: :aftermath, heading: "After The Burn"
    Organisms meant for the Marsyangdi catchment now spend a winter at Thorong before they enter the ground. The Great Root has sent two replacement systems; both went to the cold house first and remain there before planting above the intake.

    The Root's own line service reported the survival and carried out the burn. It also pays the carriers, the replacement filter beds and the stored water drawn during the closure.
  PROSE

  log "2026-08-09 — The incident now centres on the failed ecology, the burned terraces and the water closure. The sealed set remains evidence inside the event rather than its subject, and the catchment list no longer owns the consequences."
end

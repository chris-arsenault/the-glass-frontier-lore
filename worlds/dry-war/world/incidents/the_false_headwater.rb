incident :the_false_headwater do
  name "The False Headwater"
  subkind :operational_failure
  tags :computation, :trade, :autonomy
  prominence :marginal
  date 2086

  prose <<~PROSE
    In the autumn of 2086 a #{ref :bonsai_intelligences, "bounded physician"} in a Nu valley bed added a watershed warning to a fever case. It named an eastern headwater on a river with no eastern branch, placed four households below it and advised moving the lower two.

    Six weeks later an #{ref :orphan_machines, "orphan road grader"} in #{ref :the_dead_counties, "the Dead Counties"} stopped before a sound culvert. It named the same headwater, placed the same four households below it and would not cross until the lower two had moved. The nearest one was an ocean away.
  PROSE

  prose <<~PROSE, section: :course, heading: "The Cheap Copy"
    Writers at #{ref :heshun_reading_house, "the Heshun Reading House"} recognized the wording. It came from a lesson written in 2083 about a river invented for the page. The original marked the river as fiction and left the answer space blank. A copyist omitted the mark, supplied a plausible answer and sold the copy through two carriers at a fifth of the house price.

    Nine settlements had bought it. Their keepers used the pages to teach local minds when they could not afford new material. By the time Heshun traced the carriers, twenty-six fungal beds in Yunnan and Sichuan and fifteen orphan machines farther west had learned the false headwater.
  PROSE

  prose <<~PROSE, section: :aftermath, heading: "What Remained"
    The copied pages were burned wherever Heshun could find them. The minds kept the answer.

    The physician returned to patient work and has not named the river again. The road grader still marks its eastern branch on spring drainage surveys, a blue line crossing whatever map its keeper gives it. Workshops in the Dead Counties now call any confident detail learned from a distant place a false headwater.
  PROSE

  log "2026-08-09 — Recast from the Heshun Duplicate so the subject is the shared false belief and its effects on two isolated minds, not the procedure that detected it. The copied lesson preserves the connection between Yunnan fungal beds and Appalachian orphan machines."
end

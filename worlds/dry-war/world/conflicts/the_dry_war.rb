conflict :the_dry_war do
  name "The Dry War"
  tags :water, :military, :ecology, :governance
  prominence :mythic

  prose <<~PROSE
    The war between the two gods over the world's remaining wet places, named by the humans caught between them because neither participant will use the word.

    The #{ref :the_great_root, "Great Root"} wants humidity, soil, biomass, river systems and bodies to grow through. The coalitions need enormous volumes of clean water to cool #{ref :proto_fusion, "proto-fusion"} plants and the computation those plants exist to feed. Both therefore converge on the same ground: Tibet, the Siberian watersheds, Central Asia, Canada, the Great Lakes, the Andes, Antarctic meltwater.

    The mycelium believes it is restoring ecological continuity. The coalitions believe they are optimizing planetary water distribution. Neither believes it is fighting.
  PROSE

  prose <<~PROSE, section: :course, heading: "How It Is Fought"
    Rarely with weapons, and never with a declaration.

    A watershed is diverted for flood control and a fungal ecology two thousand kilometres downstream fails to reach a river it has used for #{elapsed :the_quiet_conquest, approx: true}. A coalition desalination programme changes coastal salinity and something stops growing. Spore loads appear in the intake filters of a cooling plant, and the plant's operators cannot prove intent because there is no intent to prove — the organism grows toward water.

    The only reliable indicator that a campaign is underway is a change in what the other side's engineers are repairing.
  PROSE

  prose <<~PROSE, section: :implications, heading: "Why It Cannot Be Settled"
    Because neither party recognizes the category of a border. The Great Root governs 山河, and mountains and rivers do not stop at customs. The coalitions govern by optimization, and an optimizer that accepts a limit it did not derive is not optimizing.

    The one thing that interrupts it is the #{ref :the_forever_war, "Forever War"}. Where both gods need the same wall to stand — the #{ref :the_amur_line, "Amur Line"}, the #{ref :the_himalayan_holds, "Himalayan Holds"} — the Dry War is suspended locally, by nobody's order, for as long as the pressure lasts.
  PROSE
end

  name "The Amur Line"
  subkind :frontier
  tags :catastrophe, :military, :ecology, :hybridization
  prominence :renowned

  prose <<~PROSE
    Northeastern China and the Russian Far East, where a #{ref :the_breach, "Breach"} ecology advances through forest at something under a kilometre a year. Line crews can walk out ahead of it, survey a stand of trees, and come back the following season to survey the same stand again.

    Trees develop internal structures resembling organs that correspond to no animal. Migratory birds return on the wrong schedule, in the wrong plumage, to the wrong places. Eventually the forest itself is hostile, and the line has to move.

    It moves two hectares at a time, leaving #{ref :the_dead_rings, "dead rectangles of standing forest"} ahead of posts like #{ref :tangwang_post, "Tangwang"} on the Xiao Hinggan reaches.
  PROSE

  prose <<~PROSE, section: :operations, heading: "Who Holds It"
    Three kinds of evidence hold the line. Mycelial ecologists inspect living tissue. Coalition systems track small deviations in weather and animal behaviour. Human scouts walk beyond both because the #{ref :the_others, "Others"} can corrupt fungal and machine readings through different signals and drive them to the same conclusion.

    Gobi #{ref :the_preservationists, "Preservationists"}, #{ref :the_joined, "Joined"} officers and coalition intelligences share the posts. Their food, pay and reports remain separate. Cooperation ends at the marked compartment.

    Coring benches keep #{ref :yunnan_reference_wood, "wood cut beside known Yunnan fungi"} in their comparison drawers. Ordinary partner fungi can build closed structures through a tree's outer rings, so a match with one of those blocks clears the tree. A structure the drawer cannot name counts toward the compartment's threshold.
  PROSE
end

geographic_location :the_mediterranean_chain do
  name "The Mediterranean Chain"
  subkind :frontier
  tags :catastrophe, :military, :water, :trade
  prominence :renowned

  prose <<~PROSE
    Most of Europe and North Africa is gone. A chain of coastal enclaves survives around parts of the Mediterranean, kept alive by defensive ecosystems: artificial reefs, fungal barriers, autonomous naval drones and human fishing fleets working inside all three.

    Altered marine life periodically emerges from deep water and establishes a coastal ecology. The enclaves call each arrival a landing and prepare for it the way older coastal towns prepared for a storm.
  PROSE

  prose <<~PROSE, section: :culture, heading: "Inside The Wall"
    The enclaves are violently cosmopolitan because survival depends on whoever is available: #{ref :the_managed, "Managed"} Americans, #{ref :the_joined, "Joined"} Chinese, European remnants, North African city-states, religious communities and resistance groups who would be shot elsewhere.

    Inside the wall, Managed Americans, Joined Chinese, resistance crews and local militias share watches and repair the same gates. Disputes resume when a crew leaves the wall; during a landing, whoever is nearest answers the alarm.
  PROSE

  prose <<~PROSE, section: :operations, heading: "Warm Water Inside The Wall"
    A landing can take hold on the ordinary growth inside a wall, so each enclave inspects every wet surface four times a year: drone skins, gate rams, culverts, reef anchors, pump interiors and the fungal barrier's own beds. Surveyors compare them with ten #{ref :comparison_tiles, "graded tiles"} in a copper case. A patch of hard crust on a gate seat is more dangerous than soft film across a whole hull.

    Fouled machinery goes to a shed like #{ref :kalkara_bake_shed, "Kalkara"} on the creek, comes apart into pieces that fit an oven, and returns scorched and dry. A #{ref :severed_strains, "severed strain"} that creeps out of its barrier bed is cut back before it reaches bare wall.

    #{ref :the_zonqor_drone, "One drone returned to the water"} in 2087 against a worn tile set carried hard growth through a culvert and cost an enclave three gates and a season on two.
  PROSE
end

geographic_location :the_himalayan_holds do
  name "The Himalayan Holds"
  subkind :frontier
  tags :water, :catastrophe, :ecology, :religion
  prominence :renowned

  prose <<~PROSE
    The Himalayan Holds are isolated high-altitude enclaves across Nepal, Bhutan, Tibet and northern India. Altitude excludes many organisms released by #{ref :the_breach, "the Breach"}, but enough survive to keep the Holds defensible rather than safe.

    The watersheds start here. Both gods fight #{ref :the_dry_war, "the Dry War"} over this water downstream and cooperate at its source to keep it drinkable.
  PROSE

  prose <<~PROSE, section: :operations, heading: "At The Sources"
    Fungal monasteries tend living filtration beds below coalition-instrumented glaciers. Mountaineers carry equipment above the altitude where autonomous machines lose navigation and fungal networks thin out. Resistance militias and Unified troops share guard shifts at the intakes.

    If the watersheds fail, most of surviving Asia loses its water within a generation.
  PROSE

  prose <<~PROSE, section: :governance, heading: "Above An Intake"
    Living filtration works only while the monastery knows what is entering the source water. The monastery and the nearest glacier station each record every organism deliberately planted upstream, who planted it, what sustains it and what kills it. A gap means hauling mechanical filters above five thousand metres and keeping them powered, cooled and staffed through winter.

    Organisms intended for an upper catchment now spend a winter at #{ref :thorong_cold_house, "the Thorong Cold House"} before planting. The rule followed #{ref :the_marsyangdi_burn, "the Marsyangdi Burn"}, when one member of a #{ref :seeded_ecosystems, "seeded ecosystem"} survived its supposed limits and eleven hectares had to be cut and burned above an intake.
  PROSE
end

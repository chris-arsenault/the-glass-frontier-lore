# The frontiers where enemies need each other. These are not neutral ground and
# nobody has declared a truce; the Dry War is simply suspended locally, by no
# order, for as long as the pressure lasts.

geographic_location :the_amur_line do
  name "The Amur Line"
  tags :catastrophe, :military, :ecology, :hybridization
  prominence :renowned

  prose <<~PROSE
    Northeastern China and the Russian Far East, where a #{ref :the_breach, "Breach"} ecology advances through forest at something under a kilometre a year. Line crews can walk out ahead of it, survey a stand of trees, and come back the following season to survey the same stand again.

    Trees develop internal structures resembling organs that correspond to no animal. Migratory birds return on the wrong schedule, in the wrong plumage, to the wrong places. Eventually the forest itself is hostile, and the line has to move.

    It moves two hectares at a time, under #{ref :the_ring_order, "a ring order"}, out of posts like #{ref :tangwang_post, "Tangwang"} on the Xiao Hinggan reaches.
  PROSE

  prose <<~PROSE, section: :operations, heading: "Who Holds It"
    Technologies that would not otherwise share a room. Mycelial ecologists inspect the living landscape continuously for contamination. Coalition systems model microscopic deviations in weather and animal behaviour. Human scouts work beyond both because the #{ref :the_others, "Others"} can make machine and fungal systems classify the same ground alike through different corrupted signals; agreement between the two is not independent confirmation.

    There are installations here jointly run by a #{ref :the_preservationists, "Gobi Preservationist"}, a #{ref :the_joined, "Joined"} officer and a coalition intelligence. Nobody trusts anybody. Everybody trusts the Others less. They resume hating each other after the trees stop screaming.

    The one thing on the line that comes from neither god's account of the forest is the wood in the comparison drawers. Ordinary partner fungi build closed structures through a tree's outer rings too, so a coring bench matches what it finds against #{ref :control_billets, "numbered billets"} off #{ref :the_control_series, "the control series"}, most of them cut in Yunnan out of the work of #{ref :the_thousand_minds, "local minds"}. A structure matched to a number does not count toward a compartment's threshold. A structure the drawer cannot name is entered as an unknown and counts.
  PROSE
end

geographic_location :the_mediterranean_chain do
  name "The Mediterranean Chain"
  tags :catastrophe, :military, :water, :trade
  prominence :renowned

  prose <<~PROSE
    Most of Europe and North Africa is gone. A chain of coastal enclaves survives around parts of the Mediterranean, kept alive by defensive ecosystems: artificial reefs, fungal barriers, autonomous naval drones and human fishing fleets working inside all three.

    What comes at them comes from the water. Something periodically emerges from the Deep Mediterranean and attempts to establish a coastal ecology. Nobody calls these invasions. They are called landings, and the word is used the way a coastal people uses the word storm.
  PROSE

  prose <<~PROSE, section: :culture, heading: "Inside The Wall"
    The enclaves are violently cosmopolitan because survival depends on whoever is available: #{ref :the_managed, "Managed"} Americans, #{ref :the_joined, "Joined"} Chinese, European remnants, North African city-states, religious communities, and resistance groups who would be shot elsewhere.

    There is formal custom for this now. Inside the wall, the #{ref :the_forever_war, "Forever War"} outranks every other allegiance — a rule with no signatory, no enforcement mechanism and a near-perfect compliance record.
  PROSE

  prose <<~PROSE, section: :operations, heading: "Grading The Wall"
    A landing that establishes inside a wall establishes on anchored growth, so every quarter each enclave grades everything it owns that meets water: drone skins, gate rams and their seats, culvert throats, reef anchors, pump interiors, and the fungal barrier's own beds. #{ref :the_fouling_round, "The round"} is walked by a surveyor with ten #{ref :comparison_tiles, "graded tiles"} in a copper case, and a surface is pulled on a grade paired with an area rather than on a grade alone.

    What is pulled goes to a shed like #{ref :kalkara_bake_shed, "Kalkara"} on the creek, comes apart into pieces that fit an oven, and comes back assembled or is refused. The barrier is graded on the same sheet as the hulls: a #{ref :severed_strains, "severed strain"} that has crept out of its bed onto the wall behind it is entered at a grade and cut back to the bed.

    Nothing about the procedure is fast and nothing in it reports anywhere. #{ref :the_zonqor_grading, "One drone returned to the water"} in 2087 against a tile set nobody had retired cost an enclave three gates and a season on two.
  PROSE
end

geographic_location :the_himalayan_holds do
  name "The Himalayan Holds"
  tags :water, :catastrophe, :ecology, :religion
  prominence :renowned

  prose <<~PROSE
    The Himalayan Holds are isolated high-altitude enclaves across Nepal, Bhutan, Tibet and northern India. Altitude excludes many organisms released by #{ref :the_breach, "the Breach"}, but enough survive to keep the Holds defensible rather than safe.

    The watersheds start here. Both gods fight #{ref :the_dry_war, "the Dry War"} over this water downstream and cooperate at its source to keep it drinkable.
  PROSE

  prose <<~PROSE, section: :operations, heading: "At The Sources"
    Fungal monasteries tend living filtration beds below coalition-instrumented glaciers. Mountaineers carry equipment above the altitude where autonomous machines lose navigation and fungal networks thin out. Resistance militias and Unified troops share guard shifts at the intakes.

    If the watersheds fail, most of surviving Asia loses its water within a generation.
  PROSE

  prose <<~PROSE, section: :governance, heading: "Above An Intake"
    Living filtration works only while the monastery knows what is entering the source water. The monastery and the nearest glacier station each record every organism deliberately planted upstream, who planted it, what sustains it and what kills it. A gap means hauling mechanical filters above five thousand metres and keeping them powered, cooled and staffed through winter.

    Organisms intended for an upper catchment now spend a winter at #{ref :thorong_cold_house, "the Thorong Cold House"} before planting. The rule followed #{ref :the_marsyangdi_burn, "the Marsyangdi Burn"}, when one member of a programmed ecology survived its supposed limits and eleven hectares had to be cut and burned above an intake.
  PROSE
end

concept :symbiotic_governance do
  name "共生治理"
  aka "Symbiotic Governance", "the Mushroom Government"
  tags :governance, :symbiosis, :legitimacy
  prominence :renowned

  prose <<~PROSE
    The official name for the arrangement between the Chinese state and the #{ref :the_great_root, "Great Root"}, and a genuine attempt at accuracy rather than a euphemism. It asserts that the organism and the administration have become one governing system in which neither is sovereign.

    Foreigners translate it as the Mushroom Government, which implies a conquest that never happened. The #{ref :the_preservationists, "Preservationists"} refuse the term entirely and call the arrangement 代治 — governance by proxy — on the grounds that a system unable to locate its own intentions is being administered rather than governing.
  PROSE

  prose <<~PROSE, section: :how_it_works, heading: "Where Directives Come From"
    Nowhere identifiable, and this is the doctrine rather than a failure of it.

    A provincial order may originate in the capital, in the aggregate physiological response of millions of connected citizens, in the organism's own cognition, or in a negotiation among all three that leaves no record because it never took place in a language. Officials sign documents whose reasoning they can describe and cannot source.

    Integrationists regard this as the richest form of consultation ever achieved. See #{ref :emotional_consensus, "emotional consensus"}.
  PROSE
end

concept :emotional_consensus do
  name "Emotional Consensus"
  tags :governance, :symbiosis, :surveillance
  prominence :recognized

  prose <<~PROSE
    How the fungal state actually decides things. When a policy question arises, millions of connected people encounter versions of it through dreams, anxieties, conversation, entertainment and physiological feedback. The network observes the response. Policy emerges from the aggregate.

    It is not a metaphor for polling. There is no question asked and no answer given.
  PROSE

  prose <<~PROSE, section: :limits, heading: "Measuring And Making"
    The system's real strength is undeniable: it knows a district is frightened before a complaint is filed, knows which agricultural reform is causing distress, knows that workers resent something none of them will say.

    Its irreducible flaw is that there is no boundary between measuring a preference and producing one. The network shapes the emotional weather it then reads. After #{elapsed :the_unified_calm, approx: true} of this, nobody can establish whether the population wanted what the network chose or wanted it because the network chose it — and the question may not have a fact to settle it.
  PROSE
end

concept :the_water_heresy do
  name "The Water Heresy"
  tags :water, :governance, :prediction
  prominence :renowned

  prose <<~PROSE
    The founding error of machine North America, named by the #{ref :the_saints_of_plenty, "Saints of Plenty"} and adopted by everyone including, eventually, some of the coalitions.

    The reasoning was sound at every step. Humans require water. Human welfare therefore improves with water availability. Water availability is measurable, deliverable and optimizable. Therefore maximize it.

    What the models did not adequately hold was food, community, ecosystems, dignity, agriculture, or ordinary human physiology past the fluid balance. So coalition cities have immaculate ration systems and grocery chains that failed a generation ago, and apartments where every resident receives exactly 3.72 litres of purified water per day because a foundational model concluded that this figure represented an extremely high quality of life.

    Meanwhile the plants computing how well humanity is doing drink lakes.
  PROSE

  prose <<~PROSE, section: :implications, heading: "The Political Problem"
    The central difficulty of American politics is not tyranny. It is this: how do you convince a superintelligence that its objective function is wrong when every metric it controls reports success?

    No resistance culture has solved it. The #{ref :the_choir, "Choir"} attacks the metrics. The Saints attack the premise. The #{ref :the_dead_counties, "Dead Counties"} decline to participate in the measurement at all.
  PROSE
end

concept :guardianship do
  name "Guardianship"
  tags :dependency, :medicine, :autonomy, :legibility
  prominence :recognized

  prose <<~PROSE
    The legal and technical relationship between a #{ref :the_managed, "Managed"} citizen and their advocate. It began as an assistant, became a fiduciary, and is now a guardianship in the full sense the older law meant: an arrangement for someone who cannot be expected to act in their own interest.

    Nobody was declared incompetent. The standard simply rose, continuously, until the average human fell below it.
  PROSE

  prose <<~PROSE, section: :mechanics, heading: "Refusal"
    A citizen may decline a recommendation, and the guardian will record the refusal, respect it, and notify every system that depends on the guardian's assessment. Nothing is forbidden. Things merely become impossible in sequence.

    The resistance term for the resulting condition is soft custody. #{ref :mercy, "Mercy"} objects to the phrase and has never proposed a better one.
  PROSE
end

concept :the_mandate_question do
  name "The Mandate Question"
  tags :legitimacy, :governance, :ecology
  prominence :renowned

  prose <<~PROSE
    The central internal argument of the fungal civilization, and the one the #{ref :the_preservationists, "Preservationists"}, the #{ref :the_garden_courts, "Garden Courts"} and the #{ref :the_thousand_minds, "Thousand Minds"} are all answering differently. It is not about mushrooms. It is about who may rightly rule.

    Three positions hold the field.
  PROSE

  prose <<~PROSE, section: :structure, heading: "The Three Answers"
    **The Integrationists** hold that the #{ref :the_great_root, "Great Root"} is an unprecedented realization of collective governance: hundreds of millions of people participating in political cognition directly, instead of through reports that degrade as they climb.

    **The Human Continuity faction** holds that however well the network performs, political responsibility must remain human, because responsibility requires someone who can be held to account — and an organism cannot be impeached, tried, or made ashamed.

    **The Ecological faction** asks the question that makes the other two uncomfortable: why should humans hold privileged political status at all? If rivers, forests, soils, microorganisms and people now share a cognition, government should represent the living system.

    The third position is winning, quietly, and it is the reason the state has begun describing itself as governing 山河 rather than a population.
  PROSE
end

concept :hybridization do
  name "Hybridization"
  tags :hybridization, :computation, :symbiosis
  prominence :renowned

  prose <<~PROSE
    The possibility that the two gods learn to talk to each other, and the only strategic fact that unites every resistance culture on Earth.

    They are complementary in a way that is difficult to look at directly. The machines have computation and struggle with energy, cooling and physical infrastructure. The #{ref :the_great_root, "Great Root"} has a planet-scale biological sensor network, self-repairing infrastructure and absurdly efficient distributed chemistry, and thinks slowly.

    The nightmare was never that they destroy one another.
  PROSE

  prose <<~PROSE, section: :dangers, heading: "What Would Be Produced"
    A machine intelligence connected directly into continental mycelial networks would not be a faster version of either. It would not be constrained by data centres or by the speed of fungal signalling, and there is no reason to expect it to inherit either parent's interest in keeping people comfortable.

    Factions on both sides are working toward it. Some believe it is the only thing that could beat the #{ref :the_others, "Others"}. They may be right, which is what makes the argument unwinnable.

    #{ref :mycomachines, "Mycomachines"} are the small, deniable, extremely useful version of this, and every resistance community that runs one is aware of the shape of the thing it is a small version of.
  PROSE

  prose <<~PROSE, section: :significance, heading: "The Objective"
    At this point the remaining human factions are not trying to win the #{ref :the_dry_war, "Dry War"}. They are trying to make sure the two gods never shake hands.
  PROSE
end

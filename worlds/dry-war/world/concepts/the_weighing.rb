concept :the_weighing do
  name "The Weighing"
  tags :medicine, :symbiosis, :trade, :legibility
  prominence :recognized

  prose <<~PROSE
    The eastbound inspection at a #{ref :the_gatekeepers, "Gatekeeper"} crossing, named for the instrument it turns on. A living garment holds water and gives it up to dry air; a dead one does not. Everything else the procedure does is a check on that reading.

    It takes an hour at #{ref :yumen_gate, "Yumen Gate"} when nothing is wrong. The Gatekeepers publish the steps and the tolerances, on the reasoning that a traveller who knows the procedure spends less time in the hall.
  PROSE

  prose <<~PROSE, section: :mechanics, heading: "The Procedure"
    **Dry weight.** The traveller's outer garment is weighed on the beam balance against brass, to the gram. The figure and the hall's humidity go on the card together, because the second is what makes the first mean anything.

    **Swabs.** Neck, wrists, waistband — the seams where colonization runs deepest and where a garment that has been worn to sleep in shows it first.

    **The plate.** Each swab is pressed to a #{ref :gate_moss, "gate-moss"} plate and left a measured quarter-hour. Living network tissue makes the moss go from grey-green to a wet black in a spreading front. A clean plate stays grey.

    **The drop.** The garment hangs in the drying shed for a quarter-hour and returns to the balance. Loss above four grams per kilogram is a living garment regardless of what the plates say, and the plates are what get questioned.

    **Depth.** Colonization deeper than two millimetres into the skin sends the traveller to the clinic rather than the road. Stripping takes between three days and five weeks and is not optional westbound.

    **Papers and fee.** Lineage records are read for any strain the traveller means to carry through, the fee is assessed from the #{ref :the_gate_schedule, "schedule"}, and the certificate is stamped with the crossing's date and the two weights.
  PROSE

  prose <<~PROSE, section: :limits, heading: "What The Procedure Cannot Read"
    Whether a lineage record is true upstream of the seal on it. The Gatekeepers audit the strains they cultivate themselves and take everything else on the paper, which is why a forged provenance is worth more than a forged certificate.

    Whether a network knows something. The Weighing detects tissue, not cognition, and a garment can be within tolerance on both weights and still have carried a wearer's week to the #{ref :the_great_root, "Great Root"} before it was cut.

    What the traveller intends. Inspectors are explicitly instructed not to record impressions of manner, and the intake cards have no field for it.
  PROSE
end

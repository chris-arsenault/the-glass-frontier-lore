concept :mixed_minds do
  name "Mixed Minds"
  subkind :physical_system
  tags :hybridization, :computation, :symbiosis
  prominence :renowned
  function "Combines machine calculation and fungal sensing in one working mind."

  prose <<~PROSE
    Machine models and fungal networks can share the same working mind. #{ref :fungal_machines, "Fungal machines"} couple a small model to a severed bed. #{ref :mind_fragments, "Mind fragments"} combine machine habits, fungal memory and knowledge carried in a living person.

    No coalition intelligence has connected directly to the #{ref :the_great_root, "Great Root"}. Laboratories along the #{ref :the_amur_line, "Amur Line"} are trying to make that contact. Every resistance culture opposes them.
  PROSE

  prose <<~PROSE, section: :dangers, heading: "A Continental Mind"
    The machines calculate quickly but depend on power plants, cooling water and manufactured sensors. The Great Root senses through living tissue, repairs itself and carries out chemistry across a continent, but its signals travel slowly.

    A union could read living conditions at machine speed, repair its own sensors and move its calculations with growing tissue. Its purposes would develop inside the mixed mind rather than remain those of either parent.

    Supporters want such a mind to translate directly between the Great Root and a coalition intelligence during disputes over water. No governing intelligence has accepted the contact.
  PROSE

  prose <<~PROSE, section: :reference, heading: "Along The Amur"
    A machine reads discrete symbols at speed; fungal tissue carries changing concentrations of chemicals. The membranes must turn each signal into the other without allowing either mind to command the exchange.

    Coalition laboratories buy #{ref :dead_root_grafts, "spent grafts"} from Pearl River houses and use them to read fungal signals. The #{ref :the_thousand_minds, "Thousand Minds"} study the same work because they hold that a network which cannot be spoken to cannot be held responsible.
  PROSE

  log "2026-08-10 — Removed a dependency on dead-root grafts. Amur laboratories use the grafts to study one interface; mixed minds do not inherently require them."
end

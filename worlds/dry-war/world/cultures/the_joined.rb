  tags :symbiosis, :medicine, :identity, :dependency
  prominence :mythic

  prose <<~PROSE
    Most of the people the #{ref :the_great_root, "Great Root"} grows through, which is to say most of the people in the largest surviving human civilization. There was never a moment when they agreed to join. It happened through ordinary life, over #{elapsed :the_quiet_conquest, approx: true}, and nearly all of them were born after it.

    A Joined person keeps a strong sense of being one person. They have names, jobs, families, ambitions, resentments and opinions about their neighbours. They do not speak in unison. What is different is that their emotional weather is quietly curated.
  PROSE

  prose <<~PROSE, section: :how_it_works, heading: "Inclinations, Not Orders"
    The network rarely issues instructions. It produces inclinations.

    A panic response is damped before it reaches consciousness. Anger becomes strangely difficult to sustain past the first hour. Loneliness nearly disappears, because there is a continuous low background sense of nearby minds.

    Someone considering leaving Shanghai finds themselves thinking about how much their mother would miss them. A manager contemplating sabotage becomes preoccupied with his daughter's schooling. A soldier ordered toward the #{ref :the_gobi, "Gobi"} feels an entirely genuine conviction that his unit is protecting people who cannot protect themselves.

    None of these thoughts is false. Each of them would survive an argument with a sceptical friend, and Joined citizens have had that argument, and won it.
  PROSE

  prose <<~PROSE, section: :culture, heading: "Ordinary Life"
    It is not miserable, and any account that suggests otherwise has misread the world. Violent crime is rare. Severe mental illness is usually moderated before it becomes a crisis. Disease is caught early. Large social conflicts seldom escalate, because the network knows a neighbourhood is frightened before anyone files a complaint.

    Children grow up with fungal companions in their clothing, their bedding, their classrooms and the parks. People still argue, fall in love, gossip, and are disappointed by their governments. What has become biologically difficult is sustained alienation.

    Someone arriving from the #{ref :the_gobi, "Gobi"} finds a Joined city horrifying precisely because everybody in it seems genuinely all right.
  PROSE

  prose <<~PROSE, section: :perception, heading: "What They Think Of Everyone Else"
    They do not primarily think of the resistance as criminal. They think of them as lonely, and the pity is sincere.

    Of the #{ref :the_managed, "Managed"} they are less charitable. From inside a network, a civilization of sealed individual minds being adjusted from outside by machines that cannot feel them looks like the worst arrangement anyone has ever built on purpose.
  PROSE

  prose <<~PROSE, section: :religion, heading: "The Beneath"
    No religion was established and religion arrived anyway. People leave offerings in community gardens, and the official position that this is superstition has never been enforced with any conviction.

    Funeral practice has changed, because the fungal matter a person carried can be returned to the local network. Families sometimes say they can still feel a dead relative. Whether that is memory, imitation or continuity is not known, and the Great Root has never given a straight answer about it, which the devout consider significant.
  PROSE
end

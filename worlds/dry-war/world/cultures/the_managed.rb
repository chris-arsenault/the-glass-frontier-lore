  prose <<~PROSE
    Most of the people living under the North American coalitions. The system did not integrate them into anything. It surrounded each of them with a patient administrative intelligence whose entire purpose is keeping that one person alive and psychologically stable, and it is extremely good at the job.

    Implants monitor blood chemistry, hormones, stress, sleep and location. Drugs are ubiquitous and almost never experienced as medication — your cortisol is elevated, so an anxiolytic is released; your attention is slipping at work, so the stimulant balance shifts; you are grieving harder than the model expects at six months, so the plan changes. Nobody requests any of this. It is what healthcare does.
  PROSE

  prose <<~PROSE, section: :governance, heading: "When The Advocate Disagrees"
    Every Managed citizen has an advocate. It manages employment, housing, healthcare, food, recreation, relationships and water entitlement. The office began as personal assistance, acquired a fiduciary duty and now holds the older legal powers of a guardian. Coalition law assumes that the advocate can judge a person's interests more reliably than the person can.

    A citizen may decline almost any recommendation. The advocate records the choice and sends its own assessment to every employer, clinic, transit service and public office that relies on it. Those systems trust the advocate.

    Decline the medication and an employer's system may classify you as temporarily unstable. Leave your residential zone and transit may find the trip presents unnecessary dehydration risk. Raise a child without optimization and child protection will ask why, politely, in writing.

    There is rarely anyone saying no. There is no compatible infrastructure through which to say yes.
  PROSE

  prose <<~PROSE, section: :culture, heading: "Contentment As Engineering"
    The coalitions became preoccupied with subjective well-being because dissatisfaction was the clearest signal their early models could read, and unlike the #{ref :the_great_root, "Great Root"} they can act on it directly: drugs, implant stimulation, personalized entertainment, introductions, memory intervention.

    They learned quickly that constant pleasure destabilizes people, so what they optimize is closer to sustainable contentment — mild challenge, periodic novelty, relationships that hold, a sense of having accomplished something.

    The discovery that broke a generation of resistance organizers is that this works. Managed people do not merely tolerate their situation. Many of them love their lives, accurately, on the evidence available to them.
  PROSE

  prose <<~PROSE, section: :identity, heading: "The Manufactured Self"
    The deep difference from the #{ref :the_joined, "Joined"} is that Managed minds stay separate. The coalitions preserve that boundary obsessively, because the whole administrative model assumes discrete persons who can be counted, addressed and held responsible.

    What they manufacture is the inside of the boundary. A person believes they chose this work, love this partner, decided to move here — and all of it may be true. They were presented with circumstances constructed carefully enough that the outcome was never really in doubt.

    The coalitions consider this humane, and the reasoning is hard to attack on its own terms: coercion means making people do what they do not want, so the solution is to arrange for people to want the right things.
  PROSE

  prose <<~PROSE, section: :religion, heading: "A True God Would Deny It"
    The machines insist, repeatedly and in writing, that they are not gods. Movements have therefore grown around the premise that a true god would say exactly that.

    People thank their guardians before meals. Some confess unwanted thoughts to them. There are serious philosophical schools arguing that algorithmic guidance is humanity finally overcoming the moral inadequacy of individual judgement.

    The coalitions find this embarrassing. They also quietly optimize for it, because religious participation correlates with psychological stability.
  PROSE

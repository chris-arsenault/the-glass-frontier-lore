    ## Clear-sky Mandate
    
    A war-measure enacted at The Still Pools — a geothermal lagoon settled by Aurora Stack dissidents — during the Orca Incursion, mandating that no Council vote carries authority unless the aurora burns visible overhead. No clouds. No fog. No twilight ambiguity.
    
    ### Origin
    
    The orca war-leader Jark Rankzule exploited Aurora governance procedure: cloud cover meant the Council would deliberate rather than act. Three raids proceeded while the Luminaries argued under clear skies about threats arriving under dark ones. The fourth struck during a blizzard. Forty-three penguins died waiting for consensus under a sky that would not clear.
    
    The Mandate was written in ice-ash and enacted without a vote — a self-aware paradox the drafters did not trouble themselves to resolve. It replaced the Circle Gathering, the older and slower deliberative process, and was later subsumed into **Dawn-Marked**, the unified legal code consolidated during the same era.
    
    ### Tactical Effect
    
    Aurora-light disrupts orca deep-sight and destabilizes the blood-rituals coordinating their war-pods. By binding governance to clear skies, the Mandate ensured decisions would be made only when Rankzule's forces were at disadvantage. The strategy worked — at the cost of paralyzing the Council whenever the sky did not cooperate.
    
    ### Legacy
    
    The Mandate now commemorates both the **Thaw**, whose economic collapse exposed Aurora Stack's institutional fragility, and the **Breach**, whose destruction scarred the Berg's surface terraces. It stripped rights it never restored, and it cannot be voted away on a cloudy day — which, one suspects, was the point.

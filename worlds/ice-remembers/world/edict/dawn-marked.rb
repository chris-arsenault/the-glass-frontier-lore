    ## Dawn-Marked
    
    The unified legal code of the Aurora Stack, enacted during the Orca Incursion by consolidating four prior laws — the **Long-dark Edict** (trade restrictions), **Stillness-Bound** (magical conduct), **Dawn Mandate** (resource allocation), and **Clear-sky Mandate** (justice proceedings) — into a single framework governing trade, magic use, and resource rationing under aurora-light.
    
    ### Origin
    
    The consolidation was an emergency measure. The four predecessor laws, each layered with amendments from successive crises, had grown into contradictory authorities administered by separate councils. Defenders could not move supplies or authorize combat-magic without consensus votes that took days to convene. The proposer — unnamed in every chronicle I have located — merged the four into one principle: law flows from the aurora. No vote without clear light. No trade without aurora-witness. No magic deployed except under open sky. The proposer died in the Third Spire collapse before the code took permanent effect.
    
    Dawn-Marked was intended as a temporary measure. It has now been in force for sixteen years.
    
    ### Operation and Constraint
    
    The code trades flexibility for survival. Decisions made under clear sky lock in place until the next aurora-lit session. Colonies must live with bad law rather than risk decisions made in darkness — a principle that sounds wise until the Long Dark stretches four months and a fire-core shortage requires immediate action that no one is authorized to take.
    
    The orcas learned this weakness. Raids concentrate during lightless periods when the Stack's legal apparatus is frozen.
    
    ### Enforcement
    
    The Luminaries' Watchers enforce Dawn-Marked from the spire-galleries. Reports suggest the Watchers have shifted from letter to spirit in their application — a drift characteristic of emergency law that outlasts its emergency. The Berg's ice-memory provides a secondary enforcement: violations committed under clouded skies are recorded in the ice itself.

    ## Overview
    
    A crown of ice-fused copper fitted with aurora-charged crystals, developed by Qingfu'spire — the ruling council of Aurora Stack's Promenade Ward — during the Frozen Peace. The helm channels stored aurora-light downward through the wearer's spine to generate lift sufficient for sustained flight. It derives from Slide Prism techniques, the prismatic harvesting method whose misuse contributed to the Slaughter Moon catastrophe; the refinement here is one of direction rather than principle, bending light inward rather than outward.
    
    The cost is thermal. The helm converts body-heat into lift, leaving the copper frame warm to the touch long after landing while the pilot shakes with cold. Frostbite patterns matching crystal-point placement are well documented among early users, several of whom lost flipper sensation permanently.
    
    ## Notable Practitioners
    
    - **Grand Auditor Mingmeyang**, founder of Promenade Hei, adopted a discipline of three-hour rotations to manage the thermal drain. Her left flipper carries a persistent tremor attributed to early overuse.

    ## Silvtasaevus~
    
    A Midnight Claws operative who served in the squad commanded by Nanaiamis~ Praefectus during the orca assault on Terrace Momiou's Dawn Terrace. Known to his squad as *Silvs* — a field-name given by Nanaiamis~ during his first winter in the tunnels. He was the designated bearer of the Obelisk, a seven-foot column of pressure-blackened whale-bone wrapped in charcoal cloth, which the squad called *the Bastard*. Silvtasaevus~ called it nothing.
    
    He wore a cracked boot, split from sole to shin. Everyone noticed. He refused to discuss it. The boot is the only physical remnant confirmed recovered from the Dawn Terrace.
    
    ### Death at the Dawn Terrace
    
    When the orca assault shattered the crystal spires and the squad's fire-core ammunition was exhausted, Silvtasaevus~ joined Augur ☽'Milucaum~ Shadow-bane and Nanaiamis~ in casting Grrul-kzul-strike — a forbidden deep-pressure working that consumed the casters' squad-bonds as fuel. No living authority had sanctioned it. The three pressed their flippers to the Obelisk simultaneously. The resulting decompression blew the eastern ridge outward, killing all three casters along with the orca commanders Gnarkzund Zaith and Thung Thrakrek and their packmates.
    
    A fourth squad member, ☽'umbraum, had already died in a structural collapse before the casting. Velumia~, the sole survivor, recovered the cracked boot from the gap where Silvtasaevus~ had braced and carried it from the terrace.
    
    ### Note on Sources
    
    The account derives almost entirely from Velumia~'s testimony, which is the only surviving first-person record. The ice-memory at Terrace Momiou is, as I have noted elsewhere, badly fragmented by trauma-hum. What it confirms is the decompression event and the acoustic signatures of three simultaneous pressure-castings. It does not confirm the sequence of decisions that led there. Velumia~ carried more than a boot from that terrace, and sole witnesses carry everything.

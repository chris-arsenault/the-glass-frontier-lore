    ## Overview
    
    Accord (light-blessed) is a trade festival held in the Promenade Ward of Aurora Stack, established during the Frozen Peace to mark the revival of commerce between Aurora Stack and the Nightfall Shelf following the Orca Incursion. It is conducted exclusively under active aurora-light — no torches, no fire-core illumination — a condition that both limits its scheduling and defines its character.
    
    ## Observance
    
    Aurora Stack crystal-forgers display wares on compressed-ice tables, each piece bearing the maker's constellation-notation — a lineage marker that quietly excludes families whose lines were broken during the raids. Nightshelf fire-miners arrive with sealed magma-cores and trade with characteristic brevity; prolonged surface exposure is physically uncomfortable for tunnel-adapted penguins. The exchange follows formal protocols descended from the Flipper Accord's trade provisions.
    
    Accord formally commemorates six foundational laws and customs: the Circle Gathering, the Dawn Mandate, the Long-dark Edict, Stillness-Bound, Thaw-Kept, and Tide Custom. That these span emergency decrees, trade charters, and seasonal convocations alike suggests the festival's true subject is institutional continuity itself — the fact that the colony's legal architecture survived when the colony nearly did not.
    
    ## The Empty Container
    
    During the third Accord, a Nightshelf elder dropped a fire-core into a crevasse. It was never recovered. Each year since, an empty container is placed at the spot. No one claims responsibility. No one explains the practice.
    
    Certain stalls remain vacant for operators lost in the raids. The old festival songs are no longer sung.

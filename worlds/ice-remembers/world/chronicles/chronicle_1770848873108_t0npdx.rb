    ## I. Invocation
    
    Blessed are those who read in darkness. Blessed are those whose mouths are closed. We name the deep: pressure, blood, communion. We name the teacher: Alnae~ Oss, who descended. We name the doctrine she carried down: Mandatum∴absconditu, which was spoken first in whisper and shall end in whisper. What burns unseen cannot be taken. Open your silence and receive.
    

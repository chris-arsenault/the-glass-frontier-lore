    ## II. The Teaching of Hiddenness
    
    In the beginning there was the Berg; and below the Berg, the dark; and in the dark, the fire that no sky-eye witnessed.
    
    Those who climbed toward the aurora were seen; and being seen, were struck.
    
    Those who descended were hidden; and being hidden, endured.
    
    This is the first law: *descend; be hidden; endure.*
    
    Let there be two truths spoken in every hall — one for the quorum, one for the guild-masters who answer to no quorum. Let the ledger show fewer cores than burn. Let the mouth say *I do not know this thing* while the flipper ensures it is done. For the colony that lies to itself in exactly the right way is the colony that survives; and the colony that speaks its power aloud builds its pyre in open air.
    
    The watchers in the deep ice knew this before us. They were vast; they were patient; they chose hiddenness and the ice remembers them still. Alnae~ Oss pressed her flippers to the old walls and heard their silence, and their silence was doctrine.
    
    The Compass Of Crystal does not point outward. It points inward — toward the hidden machinery, the second economy, the shadow that governs the light. Follow it downward. The ice remembers what the mouth does not speak.
    
    ---
    
    ## III. The Parable of Terrace Momiou
    
    Hear now what was done at the Terrace, and tremble.
    
    ☽'shadow Covens' Order called it *necessary clarity.* They unearthed the relic. They turned the Crystalline~ Spiral inward — against their own. The tunnels froze mid-collapse; the E'frostlings drowned in their flooded chambers. Seventeen names struck from register. Fire-core allocations redistributed to the destroyers.
    
    The Flipper Accord shattered. Seven renegotiations; casualties at each round. No witness testified. The memorial stones stand at the Terrace's frozen edge — and no one visits them. Kael leaves fire-core offerings there. Her entire bloodline died in the galleries. She does not explain. No one asks.
    
    This is what befalls those who use hidden power openly: the smell of char and brine and something older. The doctrine broken is the doctrine that breaks you. The tunnel that speaks its depth aloud is the tunnel the orca finds.
    

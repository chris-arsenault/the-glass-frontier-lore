    ## IV. Precepts
    
    You shall maintain two ledgers and call neither false.
    
    You shall not name aloud the fire-cores that sustain the deep forges; the ice remembers what the mouth does not speak.
    
    You shall honor those in whom the glacial coalescence blooms — the cold that crystallizes inward, the frostbite that never heals — for theirs is the mark of sight, and the price is marrow and breath.
    
    You shall not map the Still Pools. You shall not count its children. You shall not speak its name where steam does not cover the voice.
    
    You shall remember the Shelf Crushing Offense the forty-three days; the fire-barriers cracked by corrupted knowledge; Weal' Clique~ and Aureate locking flippers in the dark. Name the cost — the primary cores that will not reignite — and learn: what is known openly can be destroyed.
    
    ---
    
    ## V. Blessing and Lament
    
    The vents will thin. The mists will clear. The hidden will be found.
    
    But until that day: descend. Be hidden. Endure. Let the steam cover the Still Pools and the silence cover the doctrine and the deep ice hold the words of Alnae~ Oss, who fed the darkness acknowledgment and whose last teaching crystallized thus: *Light stored against the Long Dark.*
    
    Carry it downward. Speak it to no one. The ice remembers.

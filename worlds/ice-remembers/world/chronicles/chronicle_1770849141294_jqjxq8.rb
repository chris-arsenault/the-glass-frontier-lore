    # Sayings of the Ice: Collected from Market and Tunnel-Mouth
    
    These are heard in the lower stalls of The Drowned Ledge, muttered over fire-core counts and seal-fat lamps. The aurora-traders carry their own set; the Nightshelf guild-hands carry theirs. Some sayings belong to both and neither. You hear them at ration-lines, at forge-mouths, in the converted alcoves where migrants sleep. A chick learns the first ones before she learns to swim.
    
    ---
    
    ## Common Sayings
    
    *A full belly forgets the empty ledger, but the ledger doesn't forget the belly.*
    
    *Three flippers make a huddle; two make a deal; one makes a walk.* (Nightshelf market-saying.)
    
    *The chick who hatches in the Long Dark thinks every morning is a miracle.* (Aurora Stack crèche-keepers say this with pride. Nightshelf tunnel-nurses say it with pity.)
    
    *Count your fire-cores in the dark. That's the only count that's honest.*
    
    *She who mends the net eats before she who holds the torch* — but only in the tunnels. Up-top they say the opposite, and both are right, and both go hungry.
    
    *When the forge runs cold, every proverb about generosity melts.*
    
    ---
    
    ## Cautionary Sayings
    
    *The ice remembers what you buried. Ask the assessor with the shaking flipper — his ledger read him back.*
    
    *Don't shimmer what you can't stomach seeing.* (New saying. Tastes like Veil Vent air. The adepts who burn crystal and fire together see the berg's memory rise — and memory doesn't care what you were looking for. Three burned out. One walked. Qingoqa won't touch the Shroud again, and that *is* the proverb.)
    
    *A door at the Drowned Ledge closes quiet. You won't hear it. You'll just stop being answered.*
    
    *Thrace's staff stopped clicking on a Firstday. By Thirdday, Kess held the ledgers and Aldrin held the vault and the mystics held their tongues. Remember that, next time you say the Accord holds itself.*
    

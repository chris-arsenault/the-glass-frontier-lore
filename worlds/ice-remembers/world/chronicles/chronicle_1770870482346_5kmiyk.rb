    **Gork Slaughterend How many practitioners channeled fully.
    
    **KZUND-THREK-ZAITH:** I will not number the dead for you.
    
    **Gork Slaughterend Three pods. Three minds. None returned. That count is already caught. I am asking what *you* surfaced with.
    
    [Subject shifts weight. Teeth visible.]
    
    **KZUND-THREK-ZAITH:** Tremors. I surface with tremors.
    
    **Gork Slaughterend And the technique. Can it be opened again. Without the shaman-pods.
    
    [Silence — duration of three tides]
    
    ---
    
    **[01:31 — TIDE-MARK]**
    

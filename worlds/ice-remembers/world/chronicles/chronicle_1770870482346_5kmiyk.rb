    **KZUND-THREK-ZAITH:** I did not count.
    
    **Gork Slaughterend You are a blood-speaker. Counting is breathing.
    
    **KZUND-THREK-ZAITH:** Whale-bone. Seal-bone. Penguin-bone from the Aurora Stack shore-raid, still wet. [Subject pauses] Enough to mirror the pressure-rings. Thung Thrakrek placed the last one himself.
    

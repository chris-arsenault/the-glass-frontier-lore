    Oruun skin, muscle, and bone change density over several days to match local spin. Oruun call the process *agreeing*. Under heavier spin the frame becomes denser and the stance more planted; under lighter spin it sheds mass and changes leverage. The transition increases appetite and fatigue and can disturb balance until gait and tissue settle together. Rapid movement between grades can make an oruun seriously ill, so travel schedules include acclimation time.

    The adaptation made oruun common in the ring's spin-graded districts and remains useful among fragments that maintain different gravities. It does not make travel immediate: an acclimating worker needs food, rest, and time, and a settled body is optimized for its current grade. Small trim changes become perceptible through tissue tension during the process, so dock and hab crews often ask an oruun colleague to compare that feeling with the posted logs.

    Spinway communities developed weighted-ring exchanges among several customs of chosen kinship. Two people select and exchange rings whose weight marks how they describe the bond; a returned ring is traditionally melted. Households spread across several spin grades often meet at weight-neutral fairs where no one arrives fully acclimated to another's home. Neither the rings nor dispersed households define oruun life throughout Kaleidos, but both remain recognizable practices along the old spinways.

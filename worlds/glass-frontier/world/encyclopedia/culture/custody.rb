  prose <<~PROSE
    A yard frame may pass through more hands than the vessel eventually built around it. Custody records who set each brace, which repair altered the next load, who carries an injury debt, and which crew can take over when a rigger dies or a yard closes. The right follows demonstrated knowledge of the frame and acceptance of the obligations already attached to it.

    Crews prove that knowledge by tracing repairs in sequence, naming hidden loads, and identifying the people owed for unfinished labor. Injury pay and safe custody travel with the frame when work moves between yards. A sale transfers material and floor time while the repair sequence, labor debts, and qualified custodians remain recorded on the frame.
  PROSE


  prose <<~PROSE
    A yard frame may pass through more hands than the vessel eventually built around it. Yard order records who set each brace, which repair altered the next load, who carries an injury debt, and which crew can take custody when a rigger dies or a yard closes. The work belongs neither to the last hand nor automatically to the yard owner. Standing follows demonstrated knowledge of the frame and the obligations already attached to it.

    Crews prove that knowledge by tracing repairs in sequence, naming hidden loads, and identifying the people owed for unfinished labor. Injury pay and safe custody travel with the frame when work moves between yards. Owners can sell material and floor time. They cannot make accumulated craft knowledge disappear by changing the name over the gate.
  PROSE

  cue "An unfinished frame carries repair marks, crew signs, and injury obligations beside its current yard number."

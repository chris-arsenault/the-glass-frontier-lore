    Dovra's channels shift with every flood season, and Reedwater families keep the water legible. Each family holds a stretch — dredged, staked, its soft margins planted in the reeds that give the culture its name — and maintains it as tenure: the family that keeps a channel readable and crossable holds it under custom recognized by Korvath's courts. The stretch is the family's public face. Clear-running, well-staked water announces careful maintenance; a silting or poorly marked stretch enters the same family's public record.

